/* Shared presentation only: never rewrite artifact files or infer generation facts. */
(() => {
  const esc = value => window.PortalUIPrimitives.escapeHtml(value);
  const humanTokens = value => Number.isFinite(value)
    ? value >= 1e9 ? `${(value / 1e9).toFixed(1).replace(/\.0$/, '')}B`
      : value >= 1e6 ? `${(value / 1e6).toFixed(1).replace(/\.0$/, '')}M`
      : value >= 1e3 ? `${(value / 1e3).toFixed(1).replace(/\.0$/, '')}K` : String(value)
    : window.PortalI18n.t('未记录');
  function elapsedTime(job, now = Date.now()) {
    let start = null;
    for (const value of [job?.started_at, job?.created_at]) {
      if (value === null || value === undefined || value === '') continue;
      const number = Number(value);
      const candidate = Number.isFinite(number) ? number * (number < 1e12 ? 1000 : 1) : Date.parse(value);
      if (Number.isFinite(candidate) && candidate > 0 && candidate <= now) { start = candidate; break; }
    }
    if (start === null) return '';
    const seconds = Math.floor((now - start) / 1000), minutes = Math.floor(seconds / 60);
    if (seconds < 60) return window.PortalI18n.text`${seconds}s`;
    if (minutes < 60) return window.PortalI18n.text`${minutes}m ${seconds % 60}s`;
    const hours = Math.floor(minutes / 60), remainder = String(minutes % 60).padStart(2, '0');
    return window.PortalI18n.text`${hours}h ${remainder}m`;
  }
  function runningTaskText(job, now = Date.now()) {
    const key = job?.status_label_key || ({queued:'Queued', 'extracting pdf text':'Extracting PDF',
      'waiting for Resident':'Model generation', Submitting:'Submitting',
      'loading paper':'Loading paper', 'calling llm':'Model generation',
      'writing analysis':'Writing analysis', 'writing exp':'结果已生成，正在保存/核对',
      'saving result':'结果已生成，正在保存/核对', 'confirming submission':'正在确认任务状态'}[job?.step]
      || job?.step || (job?.status === 'queued' ? 'Queued' : 'Generating...'));
    return [window.PortalI18n.t(key), elapsedTime(job, now)].filter(Boolean).join(' · ');
  }
  function sourceHtml(facts = {}, {omitEmpty = false} = {}) {
    const t = value => window.PortalI18n.t(value);
    const recorded = value => !value || value === '未记录' ? t('未记录') : value;
    const resident = /^resident_[0-9a-f]{12}$/.test(facts.resident_id || '') ? facts.resident_id : '';
    const parts = [];
    if (resident) parts.push(window.PortalI18n.html`<a href="/lineage?resident=${esc(resident)}">生成 Agent：${esc(resident)}</a>`);
    else if (facts.generated_by) parts.push(`${t('Generated by')}: ${esc(facts.generated_by)}`);
    if (facts.generated_at !== undefined && facts.generated_at !== null && facts.generated_at !== '') {
      const value = facts.generated_at, numeric = Number(value);
      const date = new Date(Number.isFinite(numeric) ? numeric * (numeric < 1e12 ? 1000 : 1) : value);
      if (!Number.isNaN(date.getTime())) parts.push(`${t('Generated at')}: ${esc(date.toLocaleString(window.PortalI18n.locale?.() || window.__PORTAL_LANGUAGE__ || 'zh-CN'))}`);
    }
    if (!omitEmpty || facts.model && facts.model !== '未记录') parts.push(`${t('Paper Model')}: ${esc(recorded(facts.model))}${facts.model_evidence === 'resident_current_settings' ? t('（Resident 配置）') : ''}`);
    if (!omitEmpty || Number.isFinite(facts.total_tokens)) {
      const tokens = Number.isFinite(facts.total_tokens) ? window.PortalI18n.text`输入 ${humanTokens(facts.input_tokens)} · 输出 ${humanTokens(facts.output_tokens)} · 共 ${humanTokens(facts.total_tokens)} tokens` : t('Token 用量未记录');
      const exact = window.PortalI18n.text`输入 ${facts.input_tokens ?? t('未记录')} · 输出 ${facts.output_tokens ?? t('未记录')} · 共 ${facts.total_tokens ?? t('未记录')} tokens`;
      parts.push(`<span title="${esc(exact)}">${esc(tokens)}</span>`);
    }
    let details = '';
    if (facts.execution_id || facts.input_message_id || facts.provider || facts.account_id || facts.api_id) {
      const fields = [[t('Paper Provider'),facts.provider],[t('Paper Account'),facts.account_id],['API',facts.api_id]].filter(([,value])=>!omitEmpty || value).map(([label,value])=>`${label}: ${esc(recorded(value))}`).join(' · ');
      details = `<details><summary>${t('生成记录')}</summary>${fields}${fields?'<br>':''}${esc(facts.execution_id || '')}<br>${esc(facts.input_message_id || '')}<br>${esc(facts.model_evidence || '')}</details>`;
    }
    return parts.length || details ? `<div class="paneNote analysisProvenance">${parts.join(' · ')}${details}</div>` : '';
  }
  function expView(content) {
    const raw = String(content || '').replace(/\r\n/g,'\n');
    const header = raw.match(/^\s*---\n([\s\S]*?)\n---(?:\n|$)/);
    if (!header) return {body:raw,provenance:{}};
    const metadata = {};
    for (const line of header[1].split('\n')) {
      const match = line.match(/^([A-Za-z_]\w*):[ \t]*(.*)$/);if (!match) continue;
      let value = match[2].trim();
      if (/^".*"$/.test(value)) {try {value=JSON.parse(value);} catch (_) {continue;}}
      else if (/^'.*'$/.test(value)) value=value.slice(1,-1).replace(/''/g,"'");
      if (value && value!=='null' && value!=='~') metadata[match[1]]=value;
    }
    if (!['tfi.paper_exp.v1','dirtybase.paper_exp.v1'].includes(metadata.schema)) return {body:raw,provenance:{}};
    return {body:raw.slice(header[0].length),provenance:{generated_by:metadata.generated_by,generated_at:metadata.generated_at,resident_id:metadata.llm_resident_id || metadata.generated_by,model:metadata.llm_model,api_id:metadata.llm_api}};
  }
  function renderBody(content, paperTitle, markdown) {
    const template = document.createElement('template');template.innerHTML=markdown(content);
    const first = template.content.firstElementChild;
    const normalize = value => String(value || '').trim().replace(/\s+/g,' ').toLowerCase();
    const title=normalize(paperTitle),heading=normalize(first?.textContent);
    if (title && first?.tagName==='H1' && (heading===title || heading===`exp: ${title}`)) first.remove();
    return template.innerHTML;
  }
  window.PortalPaperArtifactPresentation = Object.freeze({sourceHtml,humanTokens,expView,renderBody,elapsedTime,runningTaskText});
})();
