"""Workspace-owned, hash-pinned explanation media; explicit generation only.

Successful bundles are not cache entries. They live below the manifest's package
directory, and are removed by the same explicit Workspace/file deletion policy.
Temporary render files are private and removed on completion/failure. All writes
use the Workspace file authorization and no-follow directory primitives.
"""
from __future__ import annotations

from contextlib import contextmanager
from collections import OrderedDict
import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import tempfile
import threading
import time
from urllib.parse import urlencode
import uuid

from management_common import secure_paths
from management_common.portal_paths import path as portal_path
from management_portal.home_explanation_plan import validate
from management_portal.home_explanation_render import render

MAX_BUNDLE = 128 * 1024 * 1024
FILES = {'video.mp4': 'video/mp4', 'captions.vtt': 'text/vtt; charset=utf-8',
         'transcript.txt': 'text/plain; charset=utf-8', 'poster.png': 'image/png'}
_VERIFIED = OrderedDict()
_VERIFIED_LOCK = threading.Lock()


def verify_stream(stream, info, digest):
    # Range/seek requests reauthorize each time, but do not repeatedly hash a
    # large unchanged video. Any replacement or in-place edit invalidates this
    # small inode fingerprint cache; it never caches an authorization decision.
    key = (info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns, info.st_ctime_ns, digest)
    with _VERIFIED_LOCK:
        if key in _VERIFIED:
            _VERIFIED.move_to_end(key)
            return
    if hashlib.file_digest(stream, 'sha256').hexdigest() != digest:
        raise ValueError('媒体文件已变化')
    stream.seek(0)
    with _VERIFIED_LOCK:
        _VERIFIED[key] = True
        while len(_VERIFIED) > 64:
            _VERIFIED.popitem(last=False)


def pointer(ref):
    if not isinstance(ref, dict):
        raise ValueError('内容引用需要地址与SHA256')
    address, digest = ref.get('address'), ref.get('sha256')
    if not isinstance(address, str) or not re.fullmatch(r'workspace_[0-9a-f]{12}/file/.+', address) or not isinstance(digest, str) or not re.fullmatch('[0-9a-f]{64}', digest):
        raise ValueError('需要正式Workspace文件地址与完整SHA256')
    root_id, relative = address.split('/file/', 1)
    parts = secure_paths.relative_parts(relative)
    from management_portal.resources.providers.folder_files import hidden
    if hidden(parts):
        raise ValueError('不能引用隐藏或敏感文件')
    return root_id, parts


class Media:
    def __init__(self, service=None, renderer=render):
        if service is None:
            from management_portal.resources import get_resource_service
            service = get_resource_service()
        self.service, self.renderer = service, renderer

    def read(self, ref, actor, limit=512*1024):
        pointer(ref)
        data, _mime, _resolved = self.service.read_content(ref['address'], actor=actor, max_bytes=limit+1)
        if len(data) > limit or hashlib.sha256(data).hexdigest() != ref['sha256']:
            raise ValueError('内容已变化或超过大小限制，请重新生成解释页引用')
        return data

    def context(self, address, sha256, actor):
        ref = {'address': address, 'sha256': sha256}
        root_id, parts = pointer(ref)
        manifest = json.loads(self.read(ref, actor))
        if not isinstance(manifest, dict) or manifest.get('schema') != 'portal-explanation/v1':
            raise ValueError('不支持的解释页')
        plan_ref = manifest.get('video_plan')
        # Generated bytes inherit the package Workspace ACL. Therefore the
        # renderer's input bytes must already belong to this exact package,
        # rather than copying a more-private external Workspace into it.
        if plan_ref:
            plan_root, plan_parts = pointer(plan_ref)
            if plan_root != root_id or plan_parts[:-1] != parts[:-1]:
                raise ValueError('视频生成计划须与解释页位于同一Workspace内容包目录')
        plan = validate(json.loads(self.read(plan_ref, actor))) if plan_ref else None
        # Authorize every contributing source on every request, including ready
        # media reads; ownership/created_by is never a substitute for permission.
        refs = [manifest.get('interaction'), manifest.get('supplement')]
        if plan and plan.get('audio'):
            audio_root, audio_parts = pointer(plan['audio'])
            if audio_root != root_id or audio_parts[:-1] != parts[:-1]:
                raise ValueError('视频音轨须与解释页位于同一Workspace内容包目录')
            refs.append(plan['audio'])
        sources = manifest.get('sources', [])
        if not isinstance(sources, list) or len(sources) > 32:
            raise ValueError('解释页来源列表超过限制')
        for source in sources:
            if isinstance(source, dict) and source.get('address'):
                self.service.resolve(source['address'], actor=actor)
        for item in refs:
            if item:
                pointer(item)
                self.service.resolve(item['address'], actor=actor)
        record = self.service.get(root_id, actor=actor)
        from management_portal.resources.providers.workspace import _root
        root = _root(record)
        output = (*parts[:-1], 'explanation-media', sha256)
        return {'ref': ref, 'root_id': root_id, 'root': root, 'output': output, 'plan': plan}

    def writable(self, ctx, actor):
        from management_portal.society_service.lineage_access_policy import workspace_reaches
        # Re-read authoritative Workspace record before each commit. A missing
        # or offline registered root must fail, never be created or relocated.
        from management_portal.resources.providers.workspace import _root
        if _root(self.service.get(ctx['root_id'], actor=actor)) != ctx['root']:
            raise PermissionError('Workspace位置已变化')
        if not workspace_reaches(actor, ctx['root_id'], write=True, path=str(ctx['root'].joinpath(*ctx['output']))):
            raise PermissionError('生成讲解视频需要此Workspace的文件写权限')

    def _state(self, ctx, actor):
        address = ctx['root_id'] + '/file/' + '/'.join((*ctx['output'], 'state.json'))
        try:
            data, _, _ = self.service.read_content(address, actor=actor, max_bytes=65537)
        except FileNotFoundError:
            return None
        if len(data) > 65536:
            raise ValueError('媒体状态无效')
        state = json.loads(data)
        if state.get('manifest_sha256') != ctx['ref']['sha256']:
            raise ValueError('媒体状态与内容版本不符')
        return state

    @staticmethod
    def active(ctx):
        try:
            with secure_paths.open_target(ctx['root'], (*ctx['output'], 'generation.lock')) as (fd, _):
                try:
                    fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
                except BlockingIOError:
                    return True
                fcntl.flock(fd, fcntl.LOCK_UN)
        except FileNotFoundError:
            pass
        return False

    def response(self, ctx, state):
        if state is None:
            return None
        result = {key: state[key] for key in ('status', 'job_id', 'chapters', 'duration', 'voice_note', 'error') if key in state}
        if result.get('status') == 'generating' and not self.active(ctx):
            # Re-read is done by status/start under the active lease; the state
            # can only change to ready while the generation lock is held.
            result.update(status='failed', error='上次生成已中断，可以重试。')
        if result.get('status') == 'ready':
            base = '/api/home-explanation/media/file?' + urlencode(ctx['ref'])
            result.update(video_url=base+'&file=video.mp4', captions_url=base+'&file=captions.vtt',
                          transcript_url=base+'&file=transcript.txt')
        return result

    def status(self, address, sha256, actor):
        ctx = self.context(address, sha256, actor)
        state = self._state(ctx, actor)
        if state and state['status'] == 'generating' and not self.active(ctx):
            state = self._state(ctx, actor)  # close finish/read race
        return self.response(ctx, state)

    def _write(self, ctx, actor, filename, data):
        self.writable(ctx, actor)
        with secure_paths.open_directory(ctx['root'], ctx['output'], create=True) as directory, secure_paths.lock_directory(directory):
            temporary = '.' + uuid.uuid4().hex + '.tmp'
            fd = secure_paths.open_child(directory, temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o664)
            try:
                with os.fdopen(fd, 'wb') as stream:
                    stream.write(data)
                    stream.flush()
                    os.fsync(stream.fileno())
                secure_paths.replace_child(directory, temporary, filename)
            finally:
                try:
                    secure_paths.unlink_child(directory, temporary)
                except FileNotFoundError:
                    pass

    def _save(self, ctx, actor, state):
        state = {**state, 'manifest_sha256': ctx['ref']['sha256']}
        self._write(ctx, actor, 'state.json', json.dumps(state, ensure_ascii=False).encode())

    def _lease(self, ctx, actor):
        self.writable(ctx, actor)
        with secure_paths.open_directory(ctx['root'], ctx['output'][:-1], create=True) as parent, secure_paths.lock_directory(parent):
            if ctx['output'][-1] not in os.listdir(parent) and len(os.listdir(parent)) >= 32:
                raise ValueError('此内容包已保留32个视频版本，请明确清理旧成果后继续')
            with secure_paths.open_directory(ctx['root'], ctx['output'], create=True) as directory:
                fd = secure_paths.open_child(directory, 'generation.lock', os.O_RDWR | os.O_CREAT, 0o664)
        try:
            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            os.close(fd)
            return None
        return fd

    @staticmethod
    def _slot():
        # Two encoding jobs across Web processes in this instance. Locks are
        # ephemeral runtime coordination, never storage for completed results.
        root = portal_path('runtime')
        with secure_paths.open_directory(root, ('explanation-media-slots',), create=True) as directory:
            for number in range(2):
                fd = secure_paths.open_child(directory, f'{number}.lock', os.O_RDWR | os.O_CREAT, 0o600)
                try:
                    fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
                    return fd
                except BlockingIOError:
                    os.close(fd)
        raise RuntimeError('视频生成繁忙，请稍后重试')

    def start(self, address, sha256, actor):
        ctx = self.context(address, sha256, actor)
        self.writable(ctx, actor)
        if ctx['plan'] is None:
            raise ValueError('此解释页没有视频生成计划')
        lease = self._lease(ctx, actor)
        if lease is None:
            return self.status(address, sha256, actor) or {'status': 'generating', 'job_id': sha256}
        slot = None
        try:
            state = self._state(ctx, actor)
            if state and state['status'] == 'ready':
                return self.response(ctx, state)
            if state and state.get('status') == 'failed' and time.time()-state.get('updated_at', 0) < 10:
                raise ValueError('生成刚刚失败，请十秒后重试')
            slot = self._slot()
            # Validate every source and its hash before accepting a job.
            audio = self.read(ctx['plan']['audio'], actor, 64*1024*1024) if ctx['plan'].get('audio') else None
            state = {'status': 'generating', 'job_id': uuid.uuid4().hex, 'updated_at': time.time()}
            self._save(ctx, actor, state)
            thread = threading.Thread(target=self._generate, args=(ctx, actor, state, audio, lease, slot), daemon=True)
            thread.start()
            lease, slot = None, None  # worker owns both leases until final commit
            return self.response(ctx, state)
        finally:
            for fd in (lease, slot):
                if fd is not None:
                    os.close(fd)

    def _generate(self, ctx, actor, state, audio, lease, slot):
        try:
            with tempfile.TemporaryDirectory(prefix='portal-explanation-') as stage:
                stage = Path(stage)
                result = self.renderer(ctx['plan'], stage, audio)
                files = {name: stage/name for name in FILES if (stage/name).is_file()}
                if not {'video.mp4', 'captions.vtt', 'transcript.txt'} <= files.keys() or sum(p.stat().st_size for p in files.values()) > MAX_BUNDLE:
                    raise ValueError('生成结果不完整或超过128MiB限制')
                # Reauthorize original sources after expensive work; revoked
                # read/write access cannot publish a completed bundle.
                self.context(ctx['ref']['address'], ctx['ref']['sha256'], actor)
                assets = {}
                for name, path in files.items():
                    data = path.read_bytes()
                    assets[name] = {'sha256': hashlib.sha256(data).hexdigest(), 'size': len(data)}
                    self._write(ctx, actor, name, data)
                self._save(ctx, actor, {**state, **result, 'assets': assets, 'status': 'ready', 'updated_at': time.time()})
                self.service.notify_source_changed(resource_id=ctx['root_id'], resource_type='workspace', kind='updated')
        except Exception:
            try:
                self._save(ctx, actor, {**state, 'status': 'failed', 'updated_at': time.time(),
                                       'error': '视频生成失败或权限已变化，请检查生成计划、音轨和媒体依赖后重试。'})
            except Exception:
                pass  # revocation must not be bypassed to record an error
        finally:
            os.close(lease)
            os.close(slot)

    @contextmanager
    def file(self, address, sha256, name, actor):
        if name not in FILES:
            raise FileNotFoundError('媒体文件不存在')
        ctx = self.context(address, sha256, actor)
        state = self._state(ctx, actor)
        if not state or state['status'] != 'ready' or name not in state.get('assets', {}):
            raise FileNotFoundError('视频尚未生成')
        output_address = ctx['root_id'] + '/file/' + '/'.join((*ctx['output'], name))
        self.service.resolve(output_address, actor=actor)
        with secure_paths.open_target(ctx['root'], (*ctx['output'], name)) as (fd, info):
            if not stat.S_ISREG(info.st_mode) or info.st_size != state['assets'][name]['size']:
                raise ValueError('媒体文件已变化')
            # Pin and verify the inode we serve, including range requests.
            with os.fdopen(os.dup(fd), 'rb') as stream:
                verify_stream(stream, info, state['assets'][name]['sha256'])
                stream.seek(0)
                yield stream, info, FILES[name]
