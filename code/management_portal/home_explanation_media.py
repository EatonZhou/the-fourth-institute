"""Workspace-owned, hash-pinned explanation media; explicit generation only.

Successful bundles are not cache entries. They live below the manifest's package
directory, and are removed by the same explicit Workspace/file deletion policy.
Temporary render files are private and removed on completion/failure. All writes
use the Workspace file authorization and no-follow directory primitives.
"""
