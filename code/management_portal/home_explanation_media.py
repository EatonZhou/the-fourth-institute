MAX_BUNDLE = 128 * 1024 * 1024
FILES = {'video.mp4': 'video/mp4', 'captions.vtt': 'text/vtt; charset=utf-8',
         'transcript.txt': 'text/plain; charset=utf-8', 'poster.png': 'image/png'}
_VERIFIED = OrderedDict()
_VERIFIED_LOCK = threading.Lock()


def verify_stream(stream, info, digest):
    # Range/seek requests reauthorize each time, but do not repeatedly hash a
    # large unchanged video. Any replacement or in-place edit invalidates this
    # small inode fingerprint cache; it never caches an authorization decision.
    key = (info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns, info.st_ctime_ns, digest)
    with _VERIFIED_LOCK:
        if key in _VERIFIED:
            _VERIFIED.move_to_end(key)
            return
    if hashlib.file_digest(stream, 'sha256').hexdigest() != digest:
        raise ValueError('媒体文件已变化')
    stream.seek(0)
    with _VERIFIED_LOCK:
        _VERIFIED[key] = True
        while len(_VERIFIED) > 64:
            _VERIFIED.popitem(last=False)


def pointer(ref):
    if not isinstance(ref, dict):
        raise ValueError('内容引用需要地址与SHA256')
    address, digest = ref.get('address'), ref.get('sha256')
    if not isinstance(address, str) or not re.fullmatch(r'workspace_[0-9a-f]{12}/file/.+', address) or not isinstance(digest, str) or not re.fullmatch('[0-9a-f]{64}', digest):
        raise ValueError('需要正式Workspace文件地址与完整SHA256')
    root_id, relative = address.split('/file/', 1)
    parts = secure_paths.relative_parts(relative)
    from management_portal.resources.providers.folder_files import hidden
    if hidden(parts):
        raise ValueError('不能引用隐藏或敏感文件')
    return root_id, parts


class Media:
    def __init__(self, service=None, renderer=render):
        if service is None:
            from management_portal.resources import get_resource_service
            service = get_resource_service()
        self.service, self.renderer = service, renderer

    def read(self, ref, actor, limit=512*1024):
        pointer(ref)
        data, _mime, _resolved = self.service.read_content(ref['address'], actor=actor, max_bytes=limit+1)
        if len(data) > limit or hashlib.sha256(data).hexdigest() != ref['sha256']:
            raise ValueError('内容已变化或超过大小限制，请重新生成解释页引用')
        return data

    def context(self, address, sha256, actor, quality='medium'):
        quality = normalize_quality(quality)
        ref = {'address': address, 'sha256': sha256}
        root_id, parts = pointer(ref)
        manifest = json.loads(self.read(ref, actor))
        if not isinstance(manifest, dict) or manifest.get('schema') != 'portal-explanation/v1':
            raise ValueError('不支持的解释页')
        plan_ref = manifest.get('video_plan')
        # Generated bytes inherit the package Workspace ACL. Therefore the
        # renderer's input bytes must already belong to this exact package,
        # rather than copying a more-private external Workspace into it.
        if plan_ref:
            plan_root, plan_parts = pointer(plan_ref)
            if plan_root != root_id or plan_parts[:-1] != parts[:-1]:
                raise ValueError('视频生成计划须与解释页位于同一Workspace内容包目录')
        plan = validate(json.loads(self.read(plan_ref, actor))) if plan_ref else None
        # Authorize every contributing source on every request, including ready
        # media reads; ownership/created_by is never a substitute for permission.
        refs = [manifest.get('interaction'), manifest.get('supplement')]
        if plan and plan.get('audio'):
            audio_root, audio_parts = pointer(plan['audio'])
            if audio_root != root_id or audio_parts[:-1] != parts[:-1]:
                raise ValueError('视频音轨须与解释页位于同一Workspace内容包目录')
            refs.append(plan['audio'])
        sources = manifest.get('sources', [])
        if not isinstance(sources, list) or len(sources) > 32:
            raise ValueError('解释页来源列表超过限制')
        for source in sources:
            if isinstance(source, dict) and source.get('address'):
                self.service.resolve(source['address'], actor=actor)
        for item in refs:
            if item:
                pointer(item)
                self.service.resolve(item['address'], actor=actor)
        record = self.service.get(root_id, actor=actor)
        from management_portal.resources.providers.workspace import _root
        root = _root(record)
        output = (*parts[:-1], 'explanation-media', sha256 if quality == 'medium' else sha256 + '-' + quality)
        return {'ref': ref, 'root_id': root_id, 'root': root, 'output': output, 'plan': plan, 'manifest': manifest, 'quality': quality,
                'owner_id': record.get('attributes', {}).get('directory', {}).get('owner_id', '')}

    def review_assets(self, ctx, generated=()):
        """Select declared fixed dependencies, never discover private siblings.

        The review owner reads and freezes these refs as the submitting actor.
        Generic provenance links (sources) are not an implicit sharing request.
        """
        manifest = ctx['manifest']
        extra = manifest.get('review_assets', [])
        if not isinstance(extra, list) or len(extra) > 32:
            raise ValueError('review_assets须为最多32个明确选定的固定文件')
        refs = [ctx['ref']]
        refs.extend(manifest[key] for key in ('interaction', 'supplement', 'video_plan', 'video') if manifest.get(key))
        video = manifest.get('video')
        if isinstance(video, dict):
            refs.extend(video[key] for key in ('captions', 'transcript') if video.get(key))
        if ctx['plan'] and ctx['plan'].get('audio'):
            refs.append(ctx['plan']['audio'])
        refs.extend(extra)
        refs.extend(generated)
        fixed = {}
        for ref in refs:
            pointer(ref)
            item = {'address': ref['address'], 'sha256': ref['sha256']}
            previous = fixed.get(item['address'])
            if previous is not None and previous != item:
                raise ValueError('同一审查文件不能声明不同摘要')
            fixed[item['address']] = item
        # Enforce the shared member-name and aggregate count contract before
        # handing the exact selection to the immutable transfer owner.
        return [{key: item[key] for key in ('address', 'sha256')}
                for item in selection(list(fixed.values()))]

    def writable(self, ctx, actor):
        from management_portal.society_service.lineage_access_policy import workspace_reaches
        # Re-read authoritative Workspace record before each commit. A missing
        # or offline registered root must fail, never be created or relocated.
        from management_portal.resources.providers.workspace import _root
        if _root(self.service.get(ctx['root_id'], actor=actor)) != ctx['root']:
            raise PermissionError('Workspace位置已变化')
        if not workspace_reaches(actor, ctx['root_id'], write=True, path=str(ctx['root'].joinpath(*ctx['output']))):
            raise PermissionError('生成讲解视频需要此Workspace的文件写权限')

    def _state(self, ctx, actor):
        address = ctx['root_id'] + '/file/' + '/'.join((*ctx['output'], 'state.json'))
        try:
            data, _, _ = self.service.read_content(address, actor=actor, max_bytes=65537)
        except FileNotFoundError:
            return None
        if len(data) > 65536:
            raise ValueError('媒体状态无效')
        state = json.loads(data)
        if state.get('manifest_sha256') != ctx['ref']['sha256'] or state.get('quality', 'medium') != ctx['quality']:
            raise ValueError('媒体状态与内容版本不符')
        return state

    @staticmethod
    def active(ctx):
        try:
            with secure_paths.open_target(ctx['root'], (*ctx['output'], 'generation.lock')) as (fd, _):
                try:
                    fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
                except BlockingIOError:
                    return True
                fcntl.flock(fd, fcntl.LOCK_UN)
        except FileNotFoundError:
            pass
        return False

    def response(self, ctx, state, actor=None):
        if state is None:
            return None
        result = {key: state[key] for key in ('status', 'job_id', 'chapters', 'duration', 'voice_note', 'error') if key in state}
        result.update(quality=ctx['quality'], policy=policy(ctx['quality']))
        if state.get('authoring'):
            result['authoring'] = state['authoring']
            if actor and result['authoring'].get('id'):
                result['authoring'] = review.AuthoringService(resources=self.service).read(result['authoring']['id'], actor) or result['authoring']
            result['quality_met'] = False
        if result.get('status') == 'generating' and not self.active(ctx):
            # Re-read is done by status/start under the active lease; the state
            # can only change to ready while the generation lock is held.
            result.update(status='failed', error='上次生成已中断，可以重试。')
        if result.get('status') == 'ready':
            base = '/api/home-explanation/media/file?' + urlencode({**ctx['ref'], 'quality': ctx['quality']})
            result.update(video_url=base+'&file=video.mp4', captions_url=base+'&file=captions.vtt',
                          transcript_url=base+'&file=transcript.txt')
            cached_review = state.get('review') or {}
            result['review'] = None
            if cached_review.get('id') and actor:
                result['review'] = review.ReviewService(resources=self.service).artifact_projection(
                    cached_review['id'], actor, ctx['ref']['address'], ctx['ref']['sha256'])
            if result['review'] is None:
                # Media caches never confer review access or prove a verdict.
                # Missing canonical records must not expose their private copy.
                result['review'] = {
                    'status': 'unavailable' if cached_review else 'not_requested',
                    'capabilities': dict.fromkeys(('can_cancel', 'can_resume', 'can_retry', 'can_read_evidence'), False)}
                if cached_review:
                    result['review']['error'] = '审查记录不可确认；不能依据媒体缓存判定质量通过。'
            result['quality_met'] = ctx['quality'] != 'high' or result['review'].get('status') == 'passed'
        return result

    def status(self, address, sha256, actor, quality='medium'):
        ctx = self.context(address, sha256, actor, quality)
        state = self._state(ctx, actor)
        if state and state['status'] == 'generating' and not self.active(ctx):
            state = self._state(ctx, actor)  # close finish/read race
        return self.response(ctx, state, actor)

    def _write(self, ctx, actor, filename, data):
        self.writable(ctx, actor)
        with secure_paths.open_directory(ctx['root'], ctx['output'], create=True) as directory, secure_paths.lock_directory(directory):
            temporary = '.' + uuid.uuid4().hex + '.tmp'
            fd = secure_paths.open_child(directory, temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o664)
            try:
                with os.fdopen(fd, 'wb') as stream:
                    stream.write(data)
                    stream.flush()
                    os.fsync(stream.fileno())
                secure_paths.replace_child(directory, temporary, filename)
            finally:
                try:
                    secure_paths.unlink_child(directory, temporary)
                except FileNotFoundError:
                    pass

    def _save(self, ctx, actor, state):
        state = {**state, 'manifest_sha256': ctx['ref']['sha256'], 'quality': ctx['quality']}
        self.writable(ctx, actor)
        with secure_paths.open_directory(ctx['root'], ctx['output'], create=True) as directory:
            fd = secure_paths.open_child(directory, 'state.lock', os.O_RDWR | os.O_CREAT, 0o600)
            try:
                fcntl.flock(fd, fcntl.LOCK_EX)
                old = self._state(ctx, actor)
                if old and old.get('status') == 'cancelled' and old.get('job_id') == state.get('job_id') and state['status'] != 'cancelled':
                    return False
                self._write(ctx, actor, 'state.json', json.dumps(state, ensure_ascii=False).encode())
                return True
            finally:
                os.close(fd)

    def _lease(self, ctx, actor):
        self.writable(ctx, actor)
        with secure_paths.open_directory(ctx['root'], ctx['output'][:-1], create=True) as parent, secure_paths.lock_directory(parent):
            if ctx['output'][-1] not in os.listdir(parent) and len(os.listdir(parent)) >= 32:
                raise ValueError('此内容包已保留32个视频版本，请明确清理旧成果后继续')
            with secure_paths.open_directory(ctx['root'], ctx['output'], create=True) as directory:
                fd = secure_paths.open_child(directory, 'generation.lock', os.O_RDWR | os.O_CREAT, 0o664)
        try:
            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            os.close(fd)
            return None
        return fd

    @staticmethod
    def _slot():
        # Two encoding jobs across Web processes in this instance. Locks are
        # ephemeral runtime coordination, never storage for completed results.
        root = portal_path('runtime')
        with secure_paths.open_directory(root, ('explanation-media-slots',), create=True) as directory:
            for number in range(2):
                fd = secure_paths.open_child(directory, f'{number}.lock', os.O_RDWR | os.O_CREAT, 0o600)
                try:
                    fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
                    return fd
                except BlockingIOError:
                    os.close(fd)
        raise RuntimeError('视频生成繁忙，请稍后重试')

    def start(self, address, sha256, actor, quality='medium', previous_review_id=None):
        ctx = self.context(address, sha256, actor, quality)
        self.writable(ctx, actor)
        existing = self._state(ctx, actor)
        if existing and existing['status'] == 'ready':
            return self.response(ctx, existing, actor)
        authored = existing.get('authoring_proof') if existing else None
        try:
            if ctx['plan'] is None:
                raise ValueError('此解释页没有视频生成计划')
            prepare_plan(ctx['plan'], quality)
            if quality != 'low' and not self.require_authored(ctx, existing, actor):
                raise ValueError('尚未完成正式质量分镜创作任务')
        except ValueError:
            if quality == 'low' or authored:
                raise
            binding = review.ReviewService(resources=self.service).package_binding(
                ctx['ref']['address'], ctx['ref']['sha256'], actor)
            authoring = review.AuthoringService(resources=self.service).submit({
                'kind': 'explanation_video', 'ref': ctx['ref']['address'], 'version': ctx['ref']['sha256'],
                'digest': ctx['ref']['sha256'], 'quality': quality, 'author': actor,
                'responsible_resident_id': binding['author'] if binding else '',
                'assets': [ctx['ref']], 'task': '修改此解释页的实际分镜，保存新manifest/plan/audio固定引用后生成视频。'}, actor)
            state = {'status': 'cancelled' if authoring['status'] == 'cancelled' else 'awaiting_authoring',
                     'job_id': authoring['id'], 'generation_actor': actor, 'authoring': authoring}
            self._save(ctx, actor, state)
            return self.response(ctx, state, actor)
        if not ctx['plan'].get('audio'):
            raise ValueError('视频需要固定音轨文件')
        if quality == 'high':
            review.ReviewService(resources=self.service).ensure_reviewers({
                'kind': 'explanation_video', 'author': actor,
                'responsible_resident_id': (authored or {}).get('resident_id', '')}, actor)
        audio = self.read(ctx['plan']['audio'], actor, 64*1024*1024)
        lease = self._lease(ctx, actor)
        if lease is None:
            return self.status(address, sha256, actor, quality) or {'status': 'generating', 'job_id': sha256, 'quality': quality}
        slot = None
        try:
            state = self._state(ctx, actor)
            if state and state['status'] == 'ready':
                return self.response(ctx, state, actor)
            if state and state.get('status') == 'failed' and time.time()-state.get('updated_at', 0) < 10:
                raise ValueError('生成刚刚失败，请十秒后重试')
            slot = self._slot()
            # Validate every source and its hash before accepting a job.
            state = {'status': 'generating', 'job_id': uuid.uuid4().hex, 'updated_at': time.time(),
                     'generation_actor': actor, 'previous_review_id': previous_review_id, 'authoring_proof': authored}
            self._save(ctx, actor, state)
            thread = threading.Thread(target=self._generate, args=(ctx, actor, state, audio, lease, slot), daemon=True)
            thread.start()
            lease, slot = None, None  # worker owns both leases until final commit
            return self.response(ctx, state)
        finally:
            for fd in (lease, slot):
                if fd is not None:
                    os.close(fd)

    def require_authored(self, ctx, state, actor):
        proof = state.get('authoring_proof') if state else None
        if not proof:
            return False
        record = review.AuthoringService(resources=self.service).read(proof['id'], actor)
        if not record or record['status'] != 'submitted' or record['subject']['quality'] != ctx['quality']:
            raise ValueError('分镜创作任务已取消或质量不匹配')
        if proof['resident_id'] != record['subject']['responsible_resident_id'] or proof['plan_digest'] != self.plan_digest(ctx['plan']):
            raise ValueError('实际计划与作者回填不符')
        return True

    @staticmethod
    def plan_digest(plan):
        # Titles and arbitrary annotations cannot stand in for actual storyboard work.
        value = None if plan is None else {key: plan.get(key) for key in ('nodes', 'audio', 'cues')}
        if value is not None:
            value['scenes'] = [{key: scene.get(key) for key in ('start', 'end', 'speech', 'visual', 'edges', 'values')}
                               for scene in plan['scenes']]
        return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False).encode()).hexdigest()

    def accept_authoring(self, address, sha256, actor, quality, authoring_id):
        ctx = self.context(address, sha256, actor, quality)
        self.writable(ctx, actor)
        service = review.AuthoringService(resources=self.service)
        with service._lock(authoring_id):
            record = service.read(authoring_id, actor)
            if not record or record['status'] != 'submitted':
                raise ValueError('创作任务不存在或已取消')
            subject = record['subject']
            if actor != subject['responsible_resident_id']:
                raise PermissionError('仅正式负责Resident可回填分镜修改')
            if subject['kind'] != 'explanation_video' or subject['quality'] != quality or subject['digest'] == sha256:
                raise ValueError('创作任务与新固定版本或质量不匹配')
            if not ctx['plan']:
                raise ValueError('新固定版本缺少分镜')
            prepare_plan(ctx['plan'], quality)
            source = self.context(subject['ref'], subject['digest'], actor, quality)
            if self.plan_digest(source['plan']) == self.plan_digest(ctx['plan']):
                raise ValueError('必须修改实际分镜或音画内容，不能只改标题、摘要或质量标签')
            previous = self._state(ctx, actor)
            if previous and previous.get('status') == 'ready':
                raise ValueError('已生成固定视频不能回填更换创作证明')
            proof = {'id': authoring_id, 'resident_id': actor, 'quality': quality,
                     'source_digest': subject['digest'], 'plan_digest': self.plan_digest(ctx['plan'])}
            state = {'status': 'authored', 'generation_actor': actor, 'authoring_proof': proof}
            self._save(ctx, actor, state)
            return {'status': 'authored', 'quality': quality, 'authoring_proof': proof, 'target': ctx['ref']}

    def _generate(self, ctx, actor, state, audio, lease, slot):
        try:
            with tempfile.TemporaryDirectory(prefix='portal-explanation-') as stage:
                stage = Path(stage)
                result = self.renderer(prepare_plan(ctx['plan'], ctx['quality']), stage, audio)
                files = {name: stage/name for name in FILES if (stage/name).is_file()}
                if not {'video.mp4', 'captions.vtt', 'transcript.txt'} <= files.keys() or sum(p.stat().st_size for p in files.values()) > MAX_BUNDLE:
                    raise ValueError('生成结果不完整或超过128MiB限制')
                # Reauthorize original sources after expensive work; revoked
                # read/write access cannot publish a completed bundle.
                self.context(ctx['ref']['address'], ctx['ref']['sha256'], actor, ctx['quality'])
                if ctx['quality'] != 'low':
                    self.require_authored(ctx, state, actor)
                self.read(ctx['plan']['audio'], actor, 64*1024*1024)
                assets = {}
                for name, path in files.items():
                    data = path.read_bytes()
                    assets[name] = {'sha256': hashlib.sha256(data).hexdigest(), 'size': len(data)}
                    self._write(ctx, actor, name, data)
                state = {**state, **result, 'assets': assets, 'status': 'ready', 'updated_at': time.time(),
                         'review': {'status': 'pending' if ctx['quality'] == 'high' else 'not_required', 'requested_by': actor}}
                if not self._save(ctx, actor, state):
                    return
                self.service.notify_source_changed(resource_id=ctx['root_id'], resource_type='workspace', kind='updated')
                if ctx['quality'] == 'high':
                    self._submit_review(ctx, actor, state)
        except Exception:
            try:
                self._save(ctx, actor, {**state, 'status': 'failed', 'updated_at': time.time(),
                                       'error': '视频生成失败或权限已变化，请检查生成计划、音轨和媒体依赖后重试。'})
            except Exception:
                pass  # revocation must not be bypassed to record an error
        finally:
            os.close(lease)
            os.close(slot)

    def _submit_review(self, ctx, actor, state):
        previous = state.get('review') or {}
        if previous.get('status') == 'submitted':
            return state
        if previous.get('requested_by', actor) != actor or state.get('generation_actor', actor) != actor:
            raise PermissionError('独立检查须由原生成或送检请求者重试')
        pending = {**previous, 'status': 'pending', 'requested_by': actor}
        try:
            ctx = self.context(ctx['ref']['address'], ctx['ref']['sha256'], actor, ctx['quality'])
            self.writable(ctx, actor)
            for name in state['assets']:
                with self.file(**ctx['ref'], name=name, actor=actor, quality=ctx['quality']):
                    pass
            owner = review.ReviewService(resources=self.service)
            if previous.get('id'):
                # A delivery retry must retain the selection already accepted
                # by the review owner, including pre-dependency-contract rounds.
                stored = owner.read(previous['id'], actor)
                if not stored:
                    raise FileNotFoundError('原审核不可确认，不能扩展旧交接')
                subject = stored['subject']
                if (subject['kind'], subject['ref'], subject['version'], subject['author']) != (
                        'explanation_video', ctx['ref']['address'], ctx['ref']['sha256'], state['generation_actor']):
                    raise ValueError('原审核不属于当前固定视频')
                pending = owner.submit(subject, actor, reviewer=stored.get('reviewer', ''))
            else:
                prefix = ctx['root_id'] + '/file/' + '/'.join(ctx['output']) + '/'
                generated = [{'address': prefix+name, 'sha256': entry['sha256']} for name, entry in sorted(state['assets'].items())]
                assets = self.review_assets(ctx, generated)
                digest = hashlib.sha256(json.dumps(assets, sort_keys=True).encode()).hexdigest()
                responsible = ''
                if state.get('authoring_proof'):
                    self.require_authored(ctx, state, actor)
                    responsible = state['authoring_proof']['resident_id']
                pending = owner.submit({
                    'kind': 'explanation_video', 'ref': ctx['ref']['address'], 'version': ctx['ref']['sha256'],
                    'digest': digest, 'quality': 'high', 'author': state['generation_actor'],
                    'responsible_resident_id': responsible, 'assets': assets,
                    'task': ctx['plan']['title'], 'previous_review_id': state.get('previous_review_id')}, actor)
        except Exception:
            pending.update(status='submission_failed', error='独立视频检查未提交，请核对检查员、固定依赖清单、摘要与当前权限；补充或修改依赖须提交新固定包，恢复旧审查不会补入新文件。')
        updated = {**state, 'review': pending}
        try:
            self._save(ctx, actor, updated)
        except Exception:
            # Preserve the last ready state when permission is revoked. A stale
            # pending state is exposed as retryable, never as passed.
            pass
        return updated

    def retry_review(self, address, sha256, actor, quality='medium'):
        ctx = self.context(address, sha256, actor, quality)
        if quality != 'high':
            raise ValueError('独立审核仅用于high；请选择high生成固定视频')
        self.writable(ctx, actor)
        state = self._state(ctx, actor)
        if not state or state.get('status') != 'ready':
            raise ValueError('视频尚未生成，无法提交独立检查')
        lease = self._lease(ctx, actor)
        if lease is None:
            return self.status(address, sha256, actor, quality)
        try:
            state = self._state(ctx, actor)
            return self.response(ctx, self._submit_review(ctx, actor, state), actor)
        finally:
            os.close(lease)

    def cancel(self, address, sha256, actor, quality='medium'):
        ctx = self.context(address, sha256, actor, quality)
        state = self._state(ctx, actor)
        if not state:
            return None
        if state.get('generation_actor') != actor:
            raise PermissionError('仅原请求者可取消生成')
        if state.get('status') == 'generating':
            self._save(ctx, actor, {**state, 'status': 'cancelled'})
        elif state.get('authoring', {}).get('id'):
            review.AuthoringService(resources=self.service).cancel(state['authoring']['id'], actor)
            self._save(ctx, actor, {**state, 'status': 'cancelled'})
        elif state.get('review', {}).get('id'):
            review.ReviewService(resources=self.service).cancel(state['review']['id'], actor)
        return self.status(address, sha256, actor, quality)

    @contextmanager
    def file(self, address, sha256, name, actor, quality='medium'):
        if name not in FILES:
            raise FileNotFoundError('媒体文件不存在')
        ctx = self.context(address, sha256, actor, quality)
        state = self._state(ctx, actor)
        if not state or state['status'] != 'ready' or name not in state.get('assets', {}):
            raise FileNotFoundError('视频尚未生成')
        output_address = ctx['root_id'] + '/file/' + '/'.join((*ctx['output'], name))
        self.service.resolve(output_address, actor=actor)
        with secure_paths.open_target(ctx['root'], (*ctx['output'], name)) as (fd, info):
            if not stat.S_ISREG(info.st_mode) or info.st_size != state['assets'][name]['size']:
                raise ValueError('媒体文件已变化')
            # Pin and verify the inode we serve, including range requests.
            with os.fdopen(os.dup(fd), 'rb') as stream:
                verify_stream(stream, info, state['assets'][name]['sha256'])
                stream.seek(0)
                yield stream, info, FILES[name]
