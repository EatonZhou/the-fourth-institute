from __future__ import annotations

import json
import re
import secrets
from datetime import datetime, timedelta, timezone
from typing import Any

from . import postgres as telepus_postgres
from .database_time import iso_time


SCHEMA_VERSION = 11
TELEGRAM_BOT_TOKEN_RE = re.compile(r"\b\d{8,12}:AA[A-Za-z0-9_-]{20,}\b")
MODES = ("assistant", "exact")


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def document(value: Any) -> str:
    """JSON text for a JSONB column."""
    text = json.dumps(value, ensure_ascii=False, sort_keys=True)
    if "\\u0000" not in text:
        return text
    # PostgreSQL text cannot hold U+0000, so JSONB rejects its escape and the
    # row would not save; the character is stored as U+FFFD instead.
    return json.dumps(_without_nul(value), ensure_ascii=False, sort_keys=True)


def _without_nul(value: Any) -> Any:
    if isinstance(value, str):
        return value.replace("\x00", "�")
    if isinstance(value, dict):
        return {_without_nul(key): _without_nul(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_without_nul(item) for item in value]
    return value


SCHEMA_DDL = """
CREATE TABLE IF NOT EXISTS meta (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

-- One row per Telegram chat: who it acts as, where its messages go and how far
-- the reply refresh has read the target's Conversation.
CREATE TABLE IF NOT EXISTS chat_state (
  chat_id TEXT PRIMARY KEY,
  chat_type TEXT NOT NULL DEFAULT '',
  telegram_user_id TEXT NOT NULL DEFAULT '',
  portal_actor TEXT NOT NULL DEFAULT '',
  mode TEXT NOT NULL DEFAULT 'assistant',
  exact_resident_id TEXT NOT NULL DEFAULT '',
  watch_resident_id TEXT NOT NULL DEFAULT '',
  watch_cursor BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);

-- Each message this chat delivered to Portal; open until its input ends.
CREATE TABLE IF NOT EXISTS telegram_inputs (
  message_id TEXT PRIMARY KEY,
  chat_id TEXT NOT NULL,
  resident_id TEXT NOT NULL,
  telegram_message_id BIGINT NOT NULL DEFAULT 0,
  excerpt TEXT NOT NULL DEFAULT '',
  open BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS telegram_inputs_open_idx ON telegram_inputs(chat_id, open);

-- Portal messages already sent to a chat; a reply is pushed once.
CREATE TABLE IF NOT EXISTS delivered_messages (
  chat_id TEXT NOT NULL,
  message_id TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (chat_id, message_id)
);

-- Which Portal message a Telegram message shows, so a Telegram reply quotes it.
CREATE TABLE IF NOT EXISTS message_links (
  chat_id TEXT NOT NULL,
  telegram_message_id BIGINT NOT NULL,
  resident_id TEXT NOT NULL,
  message_id TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (chat_id, telegram_message_id)
);

-- A question set being answered in Telegram, one question at a time.
CREATE TABLE IF NOT EXISTS question_sessions (
  session_id TEXT PRIMARY KEY,
  chat_id TEXT NOT NULL,
  resident_id TEXT NOT NULL,
  source_message_id TEXT NOT NULL,
  answer_message_id TEXT NOT NULL,
  questions_json JSONB NOT NULL,
  answers_json JSONB NOT NULL DEFAULT '{}',
  step INTEGER NOT NULL DEFAULT 0,
  lendable BOOLEAN NOT NULL DEFAULT FALSE,
  telegram_message_id BIGINT NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'open',
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  UNIQUE (chat_id, answer_message_id)
);

CREATE TABLE IF NOT EXISTS callback_tokens (
  token TEXT PRIMARY KEY,
  chat_id TEXT NOT NULL,
  payload_json JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS attachment_deliveries (
  token TEXT PRIMARY KEY,
  chat_id TEXT NOT NULL,
  telegram_user_id TEXT NOT NULL,
  portal_actor TEXT NOT NULL,
  source_message_id TEXT NOT NULL DEFAULT '',
  attachment_json JSONB NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  telegram_message_id TEXT NOT NULL DEFAULT '',
  last_error TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS audit_events (
  event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL,
  event_type TEXT NOT NULL,
  chat_id TEXT NOT NULL DEFAULT '',
  telegram_user_id TEXT NOT NULL DEFAULT '',
  portal_actor TEXT NOT NULL DEFAULT '',
  payload_json JSONB NOT NULL DEFAULT '{}'
);

CREATE TABLE IF NOT EXISTS processed_updates (
  update_id BIGINT PRIMARY KEY,
  processed_at TIMESTAMPTZ NOT NULL
);
"""


class RouterStore:
    """Bridge state in the Telepus PostgreSQL schema (``telepus_postgres``)."""

    def __init__(self, schema: str | None = None):
        self.schema = telepus_postgres.schema_name(schema)
        self._schema_ready = False

    def connect(self) -> telepus_postgres.Connection:
        return telepus_postgres.connect(self.schema, "router")

    def init_schema(self) -> None:
        if self._schema_ready:
            return
        with self.connect() as conn:
            conn.execute("BEGIN IMMEDIATE")
            version = ""
            if conn.execute("SELECT to_regclass(current_schema() || '.meta')").fetchone()[0]:
                marker = conn.execute("SELECT value FROM meta WHERE key='schema_version'").fetchone()
                if marker is None or marker[0] not in {"7", "8", "9", "10", str(SCHEMA_VERSION)}:
                    raise RuntimeError("Telepus database requires the coordinated schema migration")
                version = marker[0]
            if version != str(SCHEMA_VERSION):
                if version not in {"8", "9", "10"}:
                    conn.executescript(SCHEMA_DDL)
                    from .weixin_store import init_tables
                    init_tables(conn)
                if version != "10":
                    conn.execute("ALTER TABLE message_links ADD COLUMN IF NOT EXISTS excerpt TEXT NOT NULL DEFAULT ''")
                    from .notifications import DDL as NOTIFICATION_DDL
                    conn.executescript(NOTIFICATION_DDL)
                conn.execute("ALTER TABLE notification_deliveries ADD COLUMN IF NOT EXISTS external_message_id TEXT NOT NULL DEFAULT ''")
                conn.execute("ALTER TABLE notification_deliveries ADD COLUMN IF NOT EXISTS quote_fingerprints JSONB NOT NULL DEFAULT '[]'")
                conn.execute("ALTER TABLE notification_deliveries ADD COLUMN IF NOT EXISTS is_summary BOOLEAN NOT NULL DEFAULT FALSE")
                conn.execute(
                    "INSERT INTO meta(key, value) VALUES(?, ?) ON CONFLICT(key) DO UPDATE SET value=excluded.value",
                    ("schema_version", str(SCHEMA_VERSION)),
                )
        self._schema_ready = True

    # -- chats -------------------------------------------------------------------

    @staticmethod
    def _chat(row: Any, chat_id: str) -> dict[str, Any]:
        if not row:
            return {"chat_id": str(chat_id), "chat_type": "", "telegram_user_id": "", "portal_actor": "",
                    "mode": "assistant", "exact_resident_id": "", "watch_resident_id": "", "watch_cursor": 0}
        return {
            "chat_id": row["chat_id"], "chat_type": row["chat_type"],
            "telegram_user_id": row["telegram_user_id"], "portal_actor": row["portal_actor"],
            "mode": row["mode"] if row["mode"] in MODES else "assistant",
            "exact_resident_id": row["exact_resident_id"], "watch_resident_id": row["watch_resident_id"],
            "watch_cursor": int(row["watch_cursor"] or 0),
            "created_at": iso_time(row["created_at"]), "updated_at": iso_time(row["updated_at"]),
        }

    def get_chat_state(self, chat_id: str) -> dict[str, Any]:
        self.init_schema()
        with self.connect() as conn:
            row = conn.execute("SELECT * FROM chat_state WHERE chat_id = ?", (str(chat_id),)).fetchone()
        return self._chat(row, chat_id)

    def upsert_chat_state(self, chat_id: str, **fields: Any) -> dict[str, Any]:
        """Change the named fields of a chat; others keep their values."""
        self.init_schema()
        allowed = {"chat_type", "telegram_user_id", "portal_actor", "mode", "exact_resident_id",
                   "watch_resident_id", "watch_cursor"}
        unknown = set(fields) - allowed
        if unknown:
            raise ValueError(f"unknown chat fields: {sorted(unknown)}")
        if "mode" in fields and fields["mode"] not in MODES:
            raise ValueError("invalid chat mode")
        now = now_iso()
        with self.connect() as conn:
            conn.execute(
                "INSERT INTO chat_state(chat_id, created_at, updated_at) VALUES(?, ?, ?) ON CONFLICT(chat_id) DO NOTHING",
                (str(chat_id), now, now),
            )
            if fields:
                assignments = ", ".join(f"{name} = ?" for name in fields)
                conn.execute(
                    f"UPDATE chat_state SET {assignments}, updated_at = ? WHERE chat_id = ?",
                    (*fields.values(), now, str(chat_id)),
                )
            row = conn.execute("SELECT * FROM chat_state WHERE chat_id = ?", (str(chat_id),)).fetchone()
        return self._chat(row, chat_id)

    def watch_cursor(self, chat_id: str, resident_id: str, cursor: int) -> None:
        """Advance the refresh cursor only while the chat still watches that Resident."""
        self.init_schema()
        with self.connect() as conn:
            conn.execute(
                "UPDATE chat_state SET watch_cursor = GREATEST(watch_cursor, ?), updated_at = ? "
                "WHERE chat_id = ? AND watch_resident_id = ?",
                (int(cursor), now_iso(), str(chat_id), str(resident_id)),
            )

    def watched_chats(self, limit: int = 100, channel: str = "telegram") -> list[dict[str, Any]]:
        self.init_schema()
        with self.connect() as conn:
            rows = conn.execute(
                "SELECT * FROM chat_state WHERE watch_resident_id != '' AND channel=? ORDER BY updated_at DESC LIMIT ?",
                (channel, int(limit)),
            ).fetchall()
        return [self._chat(row, row["chat_id"]) for row in rows]

    # -- inputs and replies ----------------------------------------------------------

    def record_input(self, chat_id: str, resident_id: str, message_id: str, telegram_message_id: int,
                     excerpt: str = "") -> None:
        self.init_schema()
        now = now_iso()
        with self.connect() as conn:
            conn.execute(
                "INSERT INTO telegram_inputs(message_id, chat_id, resident_id, telegram_message_id, excerpt, open, "
                "created_at, updated_at) VALUES(?, ?, ?, ?, ?, TRUE, ?, ?) ON CONFLICT(message_id) DO NOTHING",
                (str(message_id), str(chat_id), str(resident_id), int(telegram_message_id or 0),
                 str(excerpt or ""), now, now),
            )

    def input(self, message_id: str) -> dict[str, Any] | None:
        self.init_schema()
        with self.connect() as conn:
            row = conn.execute("SELECT * FROM telegram_inputs WHERE message_id = ?", (str(message_id),)).fetchone()
        return dict(row) if row else None

    def open_inputs(self, chat_id: str, resident_id: str = "") -> list[dict[str, Any]]:
        self.init_schema()
        sql = "SELECT * FROM telegram_inputs WHERE chat_id = ? AND open"
        params: list[Any] = [str(chat_id)]
        if resident_id:
            sql += " AND resident_id = ?"
            params.append(str(resident_id))
        with self.connect() as conn:
            rows = conn.execute(sql + " ORDER BY created_at", params).fetchall()
        return [dict(row) for row in rows]

    def close_input(self, message_id: str) -> None:
        self.init_schema()
        with self.connect() as conn:
            conn.execute("UPDATE telegram_inputs SET open = FALSE, updated_at = ? WHERE message_id = ?",
                         (now_iso(), str(message_id)))

    def telegram_input_ids(self, chat_id: str, message_ids: list[str]) -> set[str]:
        if not message_ids:
            return set()
        self.init_schema()
        marks = ", ".join("?" for _ in message_ids)
        with self.connect() as conn:
            rows = conn.execute(
                f"SELECT message_id FROM telegram_inputs WHERE chat_id = ? AND message_id IN ({marks})",
                (str(chat_id), *map(str, message_ids)),
            ).fetchall()
        return {str(row["message_id"]) for row in rows}

    def claim_delivery(self, chat_id: str, message_id: str) -> bool:
        """True the first time a Portal message is pushed to this chat."""
        self.init_schema()
        with self.connect() as conn:
            cursor = conn.execute(
                "INSERT INTO delivered_messages(chat_id, message_id, created_at) VALUES(?, ?, ?) ON CONFLICT DO NOTHING",
                (str(chat_id), str(message_id), now_iso()),
            )
        return cursor.rowcount == 1

    def reopen_input(self, message_id: str) -> None:
        self.init_schema()
        with self.connect() as conn:
            conn.execute("UPDATE telegram_inputs SET open = TRUE, updated_at = ? WHERE message_id = ?",
                         (now_iso(), str(message_id)))

    def drop_question_session(self, session_id: str) -> None:
        """Forget a session whose prompt never reached Telegram, so the next refresh opens it again."""
        self.init_schema()
        with self.connect() as conn:
            conn.execute("DELETE FROM question_sessions WHERE session_id = ? AND telegram_message_id = 0",
                         (str(session_id),))

    def rewind_watch_cursor(self, chat_id: str, resident_id: str, cursor: int) -> None:
        """Move the watch cursor back after a failed send; replies already sent stay claimed."""
        self.init_schema()
        with self.connect() as conn:
            conn.execute(
                "UPDATE chat_state SET watch_cursor = LEAST(watch_cursor, ?), updated_at = ? "
                "WHERE chat_id = ? AND watch_resident_id = ?",
                (int(cursor), now_iso(), str(chat_id), str(resident_id)))

    def release_delivery(self, chat_id: str, message_id: str) -> None:
        self.init_schema()
        with self.connect() as conn:
            conn.execute("DELETE FROM delivered_messages WHERE chat_id = ? AND message_id = ?",
                         (str(chat_id), str(message_id)))

    def link_message(self, chat_id: str, telegram_message_id: int, resident_id: str, message_id: str,
                     excerpt: str = "") -> None:
        if not telegram_message_id or not message_id:
            return
        self.init_schema()
        with self.connect() as conn:
            conn.execute(
                "INSERT INTO message_links(chat_id, telegram_message_id, resident_id, message_id, created_at, excerpt) "
                "VALUES(?, ?, ?, ?, ?, ?) ON CONFLICT(chat_id, telegram_message_id) DO UPDATE SET "
                "resident_id = excluded.resident_id, message_id = excluded.message_id, excerpt = excluded.excerpt",
                (str(chat_id), int(telegram_message_id), str(resident_id), str(message_id), now_iso(), str(excerpt)),
            )

    def linked_message(self, chat_id: str, telegram_message_id: int) -> dict[str, Any] | None:
        if not telegram_message_id:
            return None
        self.init_schema()
        with self.connect() as conn:
            row = conn.execute(
                "SELECT resident_id, message_id FROM message_links WHERE chat_id = ? AND telegram_message_id = ?",
                (str(chat_id), int(telegram_message_id)),
            ).fetchone()
            if row is None:
                # Inputs accepted before inbound links were introduced remain quotable.
                row = conn.execute(
                    "SELECT resident_id, message_id FROM telegram_inputs WHERE chat_id=? AND telegram_message_id=?",
                    (str(chat_id), int(telegram_message_id)),
                ).fetchone()
        return dict(row) if row else None

    def linked_message_by_text(self, chat_id: str, excerpt: str) -> dict[str, Any] | None:
        from .quote_text import quote_text
        needle = quote_text(excerpt)
        if not needle:
            return None
        self.init_schema()
        with self.connect() as conn:
            rows = conn.execute(
                "SELECT resident_id,message_id,telegram_message_id,excerpt,created_at FROM ("
                "SELECT resident_id,message_id,telegram_message_id,excerpt,created_at FROM message_links WHERE chat_id=? "
                "UNION ALL SELECT resident_id,message_id,telegram_message_id,excerpt,created_at FROM telegram_inputs "
                "WHERE chat_id=? AND telegram_message_id<>0) AS recent ORDER BY created_at DESC LIMIT 500",
                (str(chat_id), str(chat_id)),
            ).fetchall()
        matches = {}
        for row in rows:
            if needle in quote_text(row['excerpt']):
                matches[(row['resident_id'], row['message_id'])] = dict(row)
                if len(matches) > 1:
                    return None
        return next(iter(matches.values()), None)

    # -- question sets -------------------------------------------------------------------

    @staticmethod
    def _question(row: Any) -> dict[str, Any] | None:
        if not row:
            return None
        return {
            "session_id": row["session_id"], "chat_id": row["chat_id"], "resident_id": row["resident_id"],
            "source_message_id": row["source_message_id"], "answer_message_id": row["answer_message_id"],
            "questions": row["questions_json"] if isinstance(row["questions_json"], list) else [],
            "answers": row["answers_json"] if isinstance(row["answers_json"], dict) else {},
            "step": int(row["step"] or 0), "lendable": bool(row["lendable"]),
            "telegram_message_id": int(row["telegram_message_id"] or 0), "status": row["status"],
        }

    def open_question_session(self, *, chat_id: str, resident_id: str, source_message_id: str,
                              answer_message_id: str, questions: list[dict[str, Any]], lendable: bool) -> dict[str, Any] | None:
        """A new session for this question set; None when the chat already has one for it."""
        self.init_schema()
        now = now_iso()
        session_id = "q" + secrets.token_hex(6)
        with self.connect() as conn:
            cursor = conn.execute(
                "INSERT INTO question_sessions(session_id, chat_id, resident_id, source_message_id, answer_message_id, "
                "questions_json, lendable, created_at, updated_at) VALUES(?, ?, ?, ?, ?, ?, ?, ?, ?) "
                "ON CONFLICT(chat_id, answer_message_id) DO NOTHING",
                (session_id, str(chat_id), str(resident_id), str(source_message_id), str(answer_message_id),
                 document(questions), bool(lendable), now, now),
            )
            if cursor.rowcount != 1:
                return None
            row = conn.execute("SELECT * FROM question_sessions WHERE session_id = ?", (session_id,)).fetchone()
        return self._question(row)

    def question_session(self, session_id: str, chat_id: str) -> dict[str, Any] | None:
        self.init_schema()
        with self.connect() as conn:
            row = conn.execute("SELECT * FROM question_sessions WHERE session_id = ? AND chat_id = ?",
                               (str(session_id), str(chat_id))).fetchone()
        return self._question(row)

    def question_session_for_message(self, chat_id: str, telegram_message_id: int) -> dict[str, Any] | None:
        if not telegram_message_id:
            return None
        self.init_schema()
        with self.connect() as conn:
            row = conn.execute(
                "SELECT * FROM question_sessions WHERE chat_id = ? AND telegram_message_id = ? AND status = 'open'",
                (str(chat_id), int(telegram_message_id)),
            ).fetchone()
        return self._question(row)

    def active_question(self, chat_id: str) -> dict[str, Any] | None:
        self.init_schema()
        with self.connect() as conn:
            row = conn.execute("SELECT * FROM question_sessions WHERE chat_id=? AND status='open' "
                               "ORDER BY created_at LIMIT 1", (chat_id,)).fetchone()
        return self._question(row)

    def update_question_session(self, session_id: str, **fields: Any) -> None:
        self.init_schema()
        columns = {"answers": "answers_json", "step": "step", "status": "status",
                   "telegram_message_id": "telegram_message_id"}
        values = [document(value) if name == "answers" else value for name, value in fields.items()]
        assignments = ", ".join(f"{columns[name]} = ?" for name in fields)
        with self.connect() as conn:
            conn.execute(f"UPDATE question_sessions SET {assignments}, updated_at = ? WHERE session_id = ?",
                         (*values, now_iso(), str(session_id)))

    # -- shared bookkeeping ------------------------------------------------------------------

    def append_audit(self, event_type: str, *, chat_id: str = "", telegram_user_id: str = "",
                     portal_actor: str = "", payload: dict[str, Any] | None = None) -> None:
        self.init_schema()
        with self.connect() as conn:
            conn.execute(
                "INSERT INTO audit_events(created_at, event_type, chat_id, telegram_user_id, portal_actor, payload_json) "
                "VALUES(?, ?, ?, ?, ?, ?)",
                (now_iso(), str(event_type), str(chat_id), str(telegram_user_id), str(portal_actor),
                 document(redact_sensitive(payload or {}))),
            )

    def mark_update_processed(self, update_id: int) -> bool:
        self.init_schema()
        with self.connect() as conn:
            cur = conn.execute(
                "INSERT INTO processed_updates(update_id, processed_at) VALUES(?, ?) ON CONFLICT DO NOTHING",
                (int(update_id), now_iso()),
            )
            return cur.rowcount > 0

    def get_meta(self, key: str, default: str = "") -> str:
        self.init_schema()
        with self.connect() as conn:
            row = conn.execute("SELECT value FROM meta WHERE key = ?", (str(key),)).fetchone()
        return str(row["value"]) if row else default

    def set_meta(self, key: str, value: str) -> None:
        self.init_schema()
        with self.connect() as conn:
            conn.execute(
                "INSERT INTO meta(key, value) VALUES(?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value",
                (str(key), str(value)),
            )

    def contact_actor(self, telegram_user_id: str) -> str:
        """The Portal User a Telegram user acts as, or "" when unbound.

        Portal owns ``telegram_contacts`` in this schema and writes every
        binding; the bridge only reads it.
        """
        with self.connect() as conn:
            row = conn.execute(
                "SELECT portal_actor FROM telegram_contacts WHERE telegram_user_id = ?",
                (str(telegram_user_id),),
            ).fetchone()
        return str(row["portal_actor"]) if row else ""

    def create_callback_token(self, chat_id: str, payload: dict[str, Any], ttl_seconds: int = 86400) -> str:
        self.init_schema()
        now = datetime.now(timezone.utc)
        token = secrets.token_urlsafe(6)
        with self.connect() as conn:
            conn.execute(
                "INSERT INTO callback_tokens(token, chat_id, payload_json, created_at, expires_at) VALUES(?, ?, ?, ?, ?)",
                (token, str(chat_id), document(redact_sensitive(payload)), now,
                 now + timedelta(seconds=max(60, int(ttl_seconds)))),
            )
        return token

    def get_callback_payload(self, chat_id: str, token: str) -> dict[str, Any] | None:
        self.init_schema()
        with self.connect() as conn:
            row = conn.execute(
                "SELECT payload_json, expires_at FROM callback_tokens WHERE token = ? AND chat_id = ?",
                (str(token), str(chat_id)),
            ).fetchone()
        if not row or (row["expires_at"] and row["expires_at"] < datetime.now(timezone.utc)):
            return None
        payload = row["payload_json"]
        return payload if isinstance(payload, dict) else None

    def create_attachment_delivery(self, *, chat_id: str, telegram_user_id: str, portal_actor: str,
                                   source_message_id: str, attachment: dict[str, Any], ttl_seconds: int = 86400) -> str:
        self.init_schema()
        now = datetime.now(timezone.utc)
        token = secrets.token_urlsafe(9)
        with self.connect() as conn:
            conn.execute(
                "INSERT INTO attachment_deliveries(token, chat_id, telegram_user_id, portal_actor, source_message_id, "
                "attachment_json, status, created_at, updated_at, expires_at) VALUES(?, ?, ?, ?, ?, ?, 'pending', ?, ?, ?)",
                (token, str(chat_id), str(telegram_user_id), str(portal_actor), str(source_message_id),
                 document(redact_sensitive(attachment)), now, now, now + timedelta(seconds=max(60, int(ttl_seconds)))),
            )
        return token

    def get_attachment_delivery(self, *, chat_id: str, telegram_user_id: str, portal_actor: str,
                                token: str) -> dict[str, Any] | None:
        self.init_schema()
        with self.connect() as conn:
            row = conn.execute(
                "SELECT * FROM attachment_deliveries WHERE token = ? AND chat_id = ? AND telegram_user_id = ? AND portal_actor = ?",
                (str(token), str(chat_id), str(telegram_user_id), str(portal_actor)),
            ).fetchone()
        if not row:
            return None
        status = str(row["status"] or "pending")
        if row["expires_at"] < datetime.now(timezone.utc) and status != "sent":
            status = "expired"
        attachment = row["attachment_json"]
        return {"token": str(row["token"]), "source_message_id": str(row["source_message_id"]),
                "attachment": attachment if isinstance(attachment, dict) else {}, "status": status,
                "last_error": str(row["last_error"] or "")}

    def mark_attachment_sent(self, token: str, telegram_message_id: str = "") -> None:
        self.init_schema()
        with self.connect() as conn:
            conn.execute(
                "UPDATE attachment_deliveries SET status = 'sent', telegram_message_id = ?, last_error = '', updated_at = ? WHERE token = ?",
                (str(telegram_message_id), now_iso(), str(token)),
            )

    def mark_attachment_sending(self, token: str) -> bool:
        self.init_schema()
        stale_before = datetime.now(timezone.utc) - timedelta(minutes=30)
        with self.connect() as conn:
            cursor = conn.execute(
                "UPDATE attachment_deliveries SET status = 'sending', last_error = '', updated_at = ? "
                "WHERE token = ? AND (status IN ('pending', 'failed') OR (status = 'sending' AND updated_at < ?))",
                (now_iso(), str(token), stale_before),
            )
        return cursor.rowcount == 1

    def mark_attachment_failed(self, token: str, error: str) -> None:
        self.init_schema()
        with self.connect() as conn:
            conn.execute(
                "UPDATE attachment_deliveries SET status = 'failed', last_error = ?, updated_at = ? WHERE token = ? AND status != 'sent'",
                (str(error)[:1000], now_iso(), str(token)),
            )

    def counts(self) -> dict[str, int]:
        self.init_schema()
        tables = ("chat_state", "telegram_inputs", "message_links", "question_sessions", "callback_tokens",
                  "attachment_deliveries", "audit_events", "processed_updates")
        with self.connect() as conn:
            return {table: int(conn.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]) for table in tables}


def redact_sensitive(value: Any) -> Any:
    if isinstance(value, str):
        return TELEGRAM_BOT_TOKEN_RE.sub("[telegram-bot-token-redacted]", value)
    if isinstance(value, dict):
        return {str(key): "[redacted]" if str(key).lower() in {
            "bot_token", "context_token", "qrcode", "verify_code", "typing_ticket", "aes_key", "aeskey"
        } else redact_sensitive(item) for key, item in value.items()}
    if isinstance(value, list):
        return [redact_sensitive(item) for item in value]
    return value
