"""Read an unchanged public seed from a committed release input.

Publishing derives the inventory from the selected Git tree, not the mutable
development directory. TFI_EXAMPLE_SEED selects an explicit candidate instead;
its manifest is never regenerated by this fixture.
"""
from contextlib import contextmanager
import json
import os
from pathlib import Path
import subprocess
import tarfile
import tempfile


@contextmanager
def published_seed(repository):
    repository = Path(repository)
    relative = 'instance/example_instance/seed'
    override = os.environ.get('TFI_EXAMPLE_SEED')
    if override or not (repository / '.git').exists():
        seed = Path(override) if override else repository / relative
        print(json.dumps({'seed_source': str(seed), 'kind': 'explicit' if override else 'distribution'}))
        yield seed
        return
    commit = subprocess.check_output(
        ['git', '-C', str(repository), 'rev-parse', '--verify', 'HEAD'], text=True).strip()
    with tempfile.TemporaryDirectory(prefix='published-seed-') as temporary:
        root = Path(temporary)
        with tempfile.TemporaryFile() as archive:
            subprocess.run(['git', '-C', str(repository), 'archive', '--format=tar',
                            commit + ':' + relative], stdout=archive, check=True)
            archive.seek(0)
            with tarfile.open(fileobj=archive) as contents:
                if any(not (member.isfile() or member.isdir()) for member in contents.getmembers()):
                    raise ValueError('Public seed must contain regular files and directories')
                contents.extractall(root, filter='data')
        print(json.dumps({'seed_source': str(repository), 'commit': commit, 'path': relative}))
        yield root
