const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const root = process.argv[2];
const source = fs.readFileSync(root + '/src/common/annotation-manager.js', 'utf8');
const body = source.slice(source.indexOf('class AnnotationManager'), source.lastIndexOf('export default'));
const Manager = vm.runInNewContext(body + ';AnnotationManager', {DEBOUNCE_TIME:1000, DEBOUNCE_MAX_TIME:10000, Date, setTimeout, clearTimeout});
const readerSource = fs.readFileSync(root + '/src/common/reader.js', 'utf8');
const method = readerSource.match(/getAnnotationSaveState\(\) \{[\s\S]*?\n\t\}/)[0];
const Reader = vm.runInNewContext('(class Reader {' + method + '})');
const gate = () => {let resolve;const promise = new Promise(r=>resolve=r);return {promise,resolve};};
const tick = () => new Promise(r=>setImmediate(r));
(async()=>{
 const manager = Object.assign(Object.create(Manager.prototype), {_unsavedAnnotations:new Map(),_highVolatilityAnnotationIDs:new Set(),_onSave:async()=>{},_onDelete:async()=>{}});
 const reader = new Reader();reader._annotationManager=manager;
 const state = () => JSON.parse(JSON.stringify(reader.getAnnotationSaveState()));
 assert.deepEqual(state(),{pending:false,saving:false,failed:false});
 const snapshot = reader.getAnnotationSaveState();snapshot.pending=true;
 assert.equal(state().pending,false,'caller cannot mutate owner state');
 manager._unsavedAnnotations.set('A',{id:'A',comment:'first'});
 assert.deepEqual(state(),{pending:true,saving:false,failed:false});
 const first = gate(),second = gate();let calls=0;
 manager._onSave=async values=>{calls++;await(calls===1?first.promise:second.promise);};
 const saving=manager.flush();await tick();
 assert.deepEqual(state(),{pending:false,saving:true,failed:false});
 manager._unsavedAnnotations.set('A',{id:'A',comment:'newer'});
 assert.deepEqual(state(),{pending:true,saving:true,failed:false});
 first.resolve();await tick();
 assert.equal(calls,2,'old ack must drain the newer edit');
 assert.deepEqual(state(),{pending:false,saving:true,failed:false},'old ack cannot declare the newer in-flight batch clean');
 second.resolve();await saving;
 assert.deepEqual(state(),{pending:false,saving:false,failed:false});
 manager._unsavedAnnotations.set('A',null);
 manager._onDelete=async()=>{throw Error('offline');};
 await assert.rejects(manager.flush(),/offline/);
 assert.deepEqual(state(),{pending:true,saving:false,failed:true});
 const retry=gate();manager._onDelete=()=>retry.promise;
 const retried=manager.flush();await tick();
 assert.deepEqual(state(),{pending:false,saving:true,failed:false});
 retry.resolve();await retried;
 assert.deepEqual(state(),{pending:false,saving:false,failed:false});
 console.log('PASS public save state: clean, immutable snapshot, pending/in-flight/new edit, old ack, failed delete, retry and settled');
})().catch(error=>{console.error(error);process.exitCode=1;});
