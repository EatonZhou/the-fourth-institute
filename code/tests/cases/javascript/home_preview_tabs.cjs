module.exports = async (page, assert, homeAction) => {
  const a='article_0123456789ab', b='article_abcdefabcdef', c='article_111111111111', d='article_222222222222';
  const tabs=page.locator('.homeDialoguePreview [data-portal-document-tab]');
  const address=page.locator('.homeDialoguePreview [data-portal-preview-path]');
  const open=async(resourceAddress,mode)=> {
    await page.evaluate(({resourceAddress,mode})=>PortalPreview.request({resourceAddress,mode}),{resourceAddress,mode});
    await page.waitForFunction(value=>document.querySelector('.homeDialoguePreview [data-portal-preview-path]')?.textContent.includes(value),resourceAddress);
    await page.waitForFunction(()=>document.querySelector('.homeDialogueEntry:not([hidden]) .portalFileDocument')?.textContent.includes('original'));
  };
  await open(a); assert.equal(await tabs.count(),1);
  await open(b); assert.equal(await tabs.count(),1,'ordinary open replaces the unlocked tab');
  await homeAction(page,'返回上一展示'); await page.waitForFunction(value=>document.querySelector('.homeDialoguePreview [data-portal-preview-path]').textContent.includes(value),a);
  assert.equal(await tabs.count(),1,'back follows locators without becoming another tab');
  await homeAction(page,'固定展示'); await open(b); assert.equal(await tabs.count(),2);
  assert.equal(await page.getByRole('button',{name:'解除当前文件锁定',exact:true}).getAttribute('aria-pressed'),'true','new tab inherits locking');
  await open(a); assert.equal(await tabs.count(),2,'opening an existing target activates its tab');
  await homeAction(page,'取消固定'); await open(c); assert.equal(await tabs.count(),2,'unlock replaces only the selected tab');
  await page.getByRole('button',{name:'编辑当前文件的源码',exact:true}).click(); await page.getByRole('textbox',{name:'文件草稿',exact:true}).fill('keep this draft');
  await page.evaluate(()=>{window.confirmCalls=0;PortalUI.confirm=async()=>{confirmCalls++;return false;};});
  await page.evaluate(resourceAddress=>PortalPreview.request({resourceAddress}),d);
  await page.waitForFunction(()=>confirmCalls===1);
  assert.ok((await address.textContent()).includes(c)); assert.equal(await page.getByRole('textbox',{name:'文件草稿',exact:true}).inputValue(),'keep this draft');
  assert.equal(await tabs.count(),2,'cancel keeps identity, tab set and draft');
  await open(d,'new-tab'); assert.equal(await tabs.count(),3);
  assert.equal(await page.evaluate(()=>confirmCalls),1,'explicit new tab preserves draft without discard');
  await open(c); assert.equal(await page.getByRole('textbox',{name:'文件草稿',exact:true}).inputValue(),'keep this draft');
  await homeAction(page,'取消固定');
  await page.evaluate(()=>{PortalUI.confirm=async()=>true;window.denyPreview=true;});
  await page.evaluate(resourceAddress=>PortalPreview.request({resourceAddress}),a);
  await page.getByText('当前来源不可读',{exact:true}).waitFor();
  assert.ok((await address.textContent()).includes(c)); assert.equal(await page.getByRole('textbox',{name:'文件草稿',exact:true}).inputValue(),'keep this draft','failed replacement preserves the draft');
  assert.equal(await tabs.count(),3);
  await page.evaluate(()=>{window.denyPreview=false;window.holdPreview=true;});
  await page.evaluate(resourceAddress=>PortalPreview.request({resourceAddress}),a);
  await page.waitForFunction(()=>typeof finishPreview==='function');
  await homeAction(page,'固定展示');
  await page.evaluate(()=>{window.holdPreview=false;finishPreview();});
  await page.waitForFunction(()=>document.querySelectorAll('.homeDialogueEntry').length===3);
  assert.ok((await address.textContent()).includes(c),'locking during a read protects the current document');
  await homeAction(page,'取消固定');
  await page.evaluate(()=>{window.holdPreview=true;window.finishPreview=null;});
  await page.evaluate(resourceAddress=>PortalPreview.request({resourceAddress}),a);
  await page.waitForFunction(()=>typeof finishPreview==='function');
  await page.evaluate(()=>{window.holdPreview=false;});
  await open(b); await page.evaluate(()=>finishPreview());
  await page.waitForFunction(()=>document.querySelectorAll('.homeDialogueEntry').length===3);
  assert.ok((await address.textContent()).includes(b)); assert.equal(await tabs.count(),3,'late read never replaces the newest selection');
  await page.evaluate(()=>controller.destroy());
};
