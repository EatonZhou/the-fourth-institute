const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm'), assert = require('node:assert/strict');
const context = { window: {} }; vm.createContext(context);
vm.runInContext(fs.readFileSync(path.resolve(__dirname, '../../../management_portal/static/home_dialogue_state.js'), 'utf8'), context);
const api = context.window.PortalHomeDialogueState;
let sequence = 0; const state = api.create({uuid: () => String(++sequence)});
const residentId = 'resident_0123456789ab';
const response = request_id => ({protocol:'portal-home-display/v1', request_id, version:1, view:'report', target:{kind:'lineage', id:'lineage_0123456789ab'}});
const accept = value => state.accept(value, {residentId, messageId:'new'});
const first = state.issue(residentId, ['old']);
assert.equal(accept(response(first)), null, 'unacknowledged submissions cannot trigger display');
state.acknowledge(first, residentId);
assert.equal(state.accept(response(first), {residentId, messageId:'old'}), null);
assert.equal(state.accept(response(first), {residentId:'resident_other', messageId:'new'}), null);
assert.equal(accept(response(first)).present, true);
assert.equal(accept(response(first)), null, 'duplicate result must not open twice');
let request = state.issue(residentId); state.acknowledge(request, residentId); state.manual();
assert.equal(accept(response(request)).present, false, 'manual selection wins over late results');
request = state.issue(residentId); state.acknowledge(request, residentId); state.pin(true);
assert.equal(accept(response(request)).present, false, 'pinned view is preserved'); state.pin(false);
request = state.issue(residentId); state.acknowledge(request, residentId);
assert.equal(state.accept(response(request), {residentId, messageId:'new', dirty:true}).present, false);
const old = state.issue(residentId); state.acknowledge(old, residentId);
request = state.issue(residentId); state.acknowledge(request, residentId);
assert.equal(accept(response(old)).present, false, 'older request is history only');
assert.equal(accept(response(request)).present, true);
const failed = state.issue(residentId), sent = state.issue(residentId);
assert.equal(state.acknowledge(sent, 'resident_abcdefabcdef'), false);
assert.equal(state.acknowledge('unknown', residentId), false);
assert.equal(state.acknowledge(sent, residentId), true);
assert.equal(accept(response(failed)), null, 'later success never acknowledges an earlier failed submission');
assert.equal(accept(response(sent)).present, true);
assert.equal(api.normalizeIntent({view:'report',target:{kind:'task',id:'resident_0123456789ab/msg_0123456789abcdef'}}).target.kind,'task');
assert.throws(()=>api.normalizeIntent({view:'report',target:{kind:'task',id:'task_0123456789ab'}}));
for (const invalid of [{view:'html'}, {view:'preview',target:{address:'javascript:alert(1)'}}, {view:'map',target:{kind:'task',id:'task_0123456789ab'}}]) assert.throws(() => api.normalizeIntent(invalid));
const fenced = '```portal-home-display\n' + JSON.stringify(response(request)) + '\n```';
assert.equal(api.results([{role:'user',content_parts:[{type:'text',text:fenced}]}]).length, 0);
assert.equal(api.results([{role:'assistant',content_parts:[{type:'tool_result',text:fenced}]}]).length, 0);
assert.equal(api.results([{role:'assistant',message_id:'new',content_parts:[{type:'text',text:fenced}]}]).length, 1);
const stored = {schemaVersion:3, hidden:['agent-status'], layout:{id:'kept'}, savedWorkspaces:{custom:{hidden:[], layout:{id:'saved'}}}};
const migrated = api.migrateHomeState(stored);
assert.equal(migrated.layout.id, 'kept'); assert.equal(migrated.savedWorkspaces.custom.layout.id, 'saved');
assert.ok(migrated.hidden.includes('dialogue-display')); assert.ok(migrated.savedWorkspaces.custom.hidden.includes('dialogue-display'));
assert.equal(stored.hidden.length, 1, 'migration does not mutate caller state');
assert.equal(api.migrateHomeState({contentSchemaVersion:2, hidden:[]}).hidden.length, 0, 'explicitly added component stays visible');
console.log('Home dialogue navigation, protocol and layout migration passed');
