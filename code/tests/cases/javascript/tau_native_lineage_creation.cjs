'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
module.exports=async({page,requests,errors})=>{
  const nav=page.getByRole('region',{name:'Lineage navigation',exact:true});
  await nav.getByRole('button',{name:/^Add Lineage in /}).click();
  const form=page.getByRole('dialog',{name:'New Lineage',exact:true});
  await form.getByRole('textbox',{name:'Name (optional)',exact:true}).fill('New Sample Lineage');
  await form.getByRole('checkbox').uncheck();
  await form.getByRole('button',{name:'Create Lineage',exact:true}).click();
  const node=page.getByRole('dialog',{name:'New node',exact:true});
  await node.getByRole('textbox',{name:'Agent name',exact:true}).waitFor({state:'visible'});
  assert.equal(requests.filter(r=>r.instruction==='CreateLineage').length,1);
  assert.equal(requests.filter(r=>r.instruction==='CreateResident').length,0);
  const hatg=page.getByRole('region',{name:'HATG',exact:true});
  // Old preparation clicked the toolbar behind the automatically opened modal.
  await assert.rejects(hatg.getByRole('button',{name:/^New node:/}).click({timeout:200}),/Timeout/);
  assert.equal(await node.isVisible(),true);
  const prompt=fs.readFileSync(path.join(__dirname,'../../../management_portal/test_framework/config/tau_runner_prompt.md'),'utf8');
  const controls=prompt.match(/```js\n(\/\/ tau-current-controls\n[\s\S]*?)\n```/);
  assert.ok(controls,'the dynamic tab contract must distinguish gone from ambiguous');
  const currentNativeTab=new Function(controls[1]+'; return currentNativeTab;')();
  assert.ok(prompt.includes('CreateLineage成功后原生页面会自动打开首个New node表单'),
    'public preparation must account for the native automatically opened form');
  await node.getByRole('button',{name:'Cancel',exact:true}).click();
  await node.waitFor({state:'hidden'});
  const tab=page.locator('[data-portal-workbench-tab="navigation"]');
  assert.equal(await (await currentNativeTab(page,'Lineage navigation')).getAttribute('data-portal-workbench-tab'),'navigation');
  const oldBox=await tab.boundingBox();
  await page.mouse.move(oldBox.x+oldBox.width/2,oldBox.y+1);
  const close=page.getByRole('button',{name:'Close Lineage navigation',exact:true});
  await assert.rejects(close.click({timeout:200}),/Timeout/);
  const {revealWorkbenchTabControls}=require('../../../management_portal/test_framework/tau_workbench_tabs');
  const samples=[];
  const ready=await revealWorkbenchTabControls(tab,{record:s=>samples.push(s)});
  assert.ok(ready.ready && samples.length>=2);
  assert.equal(ready.candidates[0].close.label,'Close Lineage navigation');
  const documented=prompt.match(/```js\n(\/\/ tau-native-tab-close\n[\s\S]*?)\n```/);
  assert.ok(documented, 'public tab preparation must show the executable snapshot-to-locator contract');
  const documentedClose=new Function('page','snapshot',documented[1]+'\nreturn nativeTabCloseLocator(page,snapshot);');
  assert.throws(()=>documentedClose(page,{...ready,ready:false}),/not ready/);
  assert.throws(()=>documentedClose(page,{...ready,candidates:[...ready.candidates,...ready.candidates]}),/not ready/);
  await documentedClose(page,ready).click();
  await tab.waitFor({state:'hidden'});
  assert.equal(await currentNativeTab(page,'Lineage navigation'),null,'an indirectly removed cached tab is already absent');
  assert.deepEqual(errors,[]);
};
