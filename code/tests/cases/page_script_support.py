"""The Portal globals each page script uses, and the scripts a page loads.

Portal pages load classic scripts, and nearly every script wraps itself in a
function and shares its object through a property of ``window``:
``window.PortalAPI = {...}`` provides PortalAPI, ``window.PortalAPI.get(...)``
uses it.  The IIFE parameter that receives ``window`` (``(function (global)
{...})(window)``) counts as ``window``.  A script *needs* a global when it uses
it without first testing for it anywhere: ``window.X?.y``, ``typeof
window.X``, ``if (window.X)``, ``window.X && ...``, or passing ``window.X``
along as a value make the global optional for the whole script.

A script may load others on demand: a string naming a script path
(``"/static/portal_scope_menu.js"``), or a loader table entry naming a script
and the global it provides (``["principal_backpack", "PortalPrincipalBackpack"]``),
makes that script's globals available to the page.  What a script loaded on
demand needs is checked only on the pages that list it: when it is loaded
depends on what the user does, which a static reading does not see.  Neither
is load order checked; a global used at load time must come from an earlier
script, and finding the uses that run at load time takes more than tokens.

A page is a Portal document as the server sends it: its script groups
expanded (``script_groups.py``), the page bootstrap with the site script
inlined (``page_bootstrap.py``), Home with the features' panels
(``web.home_panel``), the Knowledge board (``page_renderers.py``), and each
feature's native view (``web.native_view``)
inside the Workbenches page that mounts it (``development_workspace.js``).
``/static/portal_resource_routes.js`` is generated by the server
(``portal_route_script``).  Vendor libraries are not scanned.
"""
from __future__ import annotations

from dataclasses import dataclass, field
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
PORTAL = ROOT / "management_portal"
STATIC = PORTAL / "static"
# Test page scripts are served under /static as well.
SCRIPT_ROOTS = (STATIC, PORTAL / "test_framework" / "page")
UNSCANNED = ("vendor/", "projection_libraries/")
GENERATED = "portal_resource_routes.js"
NATIVE_VIEW_HOST = "workbenches.html"

WINDOW_NAMES = frozenset({"window", "globalThis", "self"})
# Browser objects that test frames replace; they are never a Portal script's to provide.
BROWSER_GLOBALS = frozenset({
    "fetch", "localStorage", "sessionStorage", "open", "showOpenFilePicker", "showSaveFilePicker", "katex",
})
_ASSIGNMENTS = frozenset({"=", "??=", "||=", "&&="})
_TESTED_BEFORE = frozenset({"typeof", "!", "in", "delete"})
_TESTED_AFTER = frozenset({"?.", "&&", "||", "??", "?", "===", "!==", "==", "!=", ")", ",", ";", "]", ":", "}"})

_IDENTIFIER = re.compile(r"[A-Za-z_$À-￿][A-Za-z0-9_$À-￿]*")
_NUMBER = re.compile(r"0[xXoObB][0-9a-fA-F_]+n?|\d[\d_]*\.?[\d_]*(?:[eE][+-]?\d+)?n?|\.\d[\d_]*(?:[eE][+-]?\d+)?")
_PUNCTUATORS = sorted(
    ">>>= ... === !== **= <<= >>= >>> ?. ?? ??= &&= ||= => == != <= >= && || ++ -- += -= *= /= %= &= |= ^= "
    "<< >> ** { } ( ) [ ] ; , < > + - * / % & | ^ ! ~ ? : = . @ #".split(), key=len, reverse=True)
# After these a "/" starts a regular expression rather than a division.
_REGEX_AFTER_WORDS = frozenset({
    "return", "typeof", "instanceof", "in", "of", "new", "delete", "void", "throw", "case", "do", "else", "yield", "await",
})
_SPACE = frozenset(" \t\r\n﻿   ")


def tokens(source: str) -> list[tuple[str, str, int]]:
    """``(kind, text, offset)`` for each token: ``name``, ``number``, ``string``, ``template``, ``regex`` or ``punct``.

    Strings, template text and regular expressions come out whole, so their
    content is never read as code; the code inside ``${...}`` is.
    """
    out: list[tuple[str, str, int]] = []
    templates: list[int] = []  # brace depth at each open ``${``
    depth = 0
    i, end = 0, len(source)

    def emit(kind: str, text: str, offset: int) -> None:
        out.append((kind, text, offset))

    while i < end:
        char = source[i]
        if char in _SPACE:
            i += 1
        elif source.startswith("//", i):
            newline = source.find("\n", i)
            i = end if newline < 0 else newline
        elif source.startswith("/*", i):
            close = source.find("*/", i + 2)
            i = end if close < 0 else close + 2
        elif char in "'\"":
            j = i + 1
            while j < end and source[j] != char:
                j += 2 if source[j] == "\\" else 1
            emit("string", source[i + 1:j], i)
            i = j + 1
        elif char == "`" or (char == "}" and templates and templates[-1] == depth):
            if char == "}":
                templates.pop()
            j = i + 1
            while j < end:
                if source[j] == "\\":
                    j += 2
                elif source[j] == "`":
                    j += 1
                    break
                elif source.startswith("${", j):
                    templates.append(depth)
                    j += 2
                    break
                else:
                    j += 1
            # Code inside ``${`` starts an expression, as after "(".
            emit("template" if not source.startswith("${", j - 2) else "punct", source[i:j], i)
            i = j
        elif char == "/" and _regex_may_start(out):
            j, in_class = i + 1, False
            while j < end and source[j] != "\n":
                if source[j] == "\\":
                    j += 2
                    continue
                if source[j] == "[":
                    in_class = True
                elif source[j] == "]":
                    in_class = False
                elif source[j] == "/" and not in_class:
                    break
                j += 1
            j += 1
            while j < end and source[j].isalnum():
                j += 1
            emit("regex", source[i:j], i)
            i = j
        elif match := _IDENTIFIER.match(source, i):
            emit("name", match.group(), i)
            i = match.end()
        elif (match := _NUMBER.match(source, i)) and match.end() > i:
            emit("number", match.group(), i)
            i = match.end()
        else:
            for punctuator in _PUNCTUATORS:
                if source.startswith(punctuator, i):
                    # "a?.5:b" is a conditional, not optional chaining.
                    if punctuator == "?." and source[i + 2:i + 3].isdigit():
                        punctuator = "?"
                    depth += {"{": 1, "}": -1}.get(punctuator, 0)
                    emit("punct", punctuator, i)
                    i += len(punctuator)
                    break
            else:
                raise SyntaxError(f"unexpected {char!r} at offset {i}")
    return out


def _regex_may_start(previous: list[tuple[str, str, int]]) -> bool:
    if not previous:
        return True
    kind, text, _offset = previous[-1]
    if kind == "punct":
        return text not in (")", "]", "}", "++", "--")
    return kind == "name" and text in _REGEX_AFTER_WORDS


@dataclass
class ScriptGlobals:
    name: str
    provides: set[str] = field(default_factory=set)
    # global -> line of its first use
    needs: dict[str, int] = field(default_factory=dict)
    loads: set[str] = field(default_factory=set)
    # (script, global) named together by a loader table; kept when the script provides the global
    loader_entries: set[tuple[str, str]] = field(default_factory=set)


def scan(name: str, source: str, scripts: set[str]) -> ScriptGlobals:
    """The globals ``source`` provides and needs, and the scripts of ``scripts`` it loads on demand."""
    found = tokens(source)
    names = WINDOW_NAMES | _window_parameter(found)
    result = ScriptGlobals(name)
    uses: dict[str, list[int]] = {}
    tested: set[str] = set()
    for k, (kind, text, offset) in enumerate(found):
        if kind == "string":
            path = re.fullmatch(r"(?:/static/)?([A-Za-z0-9_/]+\.js)", text)
            if path and path.group(1) in scripts and path.group(1) != name:
                result.loads.add(path.group(1))
            elif (re.fullmatch(r"[a-z0-9_]+", text) and f"{text}.js" in scripts and k + 2 < len(found)
                  and found[k + 1][1] == "," and found[k + 2][0] == "string"):
                result.loader_entries.add((f"{text}.js", found[k + 2][1]))
            continue
        if kind != "name" or text not in names or (k and found[k - 1][1] in (".", "?.")):
            continue
        if k + 2 >= len(found) or found[k + 1][1] not in (".", "?.") or found[k + 2][0] != "name":
            continue
        member = found[k + 2][1]
        after = found[k + 3][1] if k + 3 < len(found) else ""
        if after in _ASSIGNMENTS:
            result.provides.add(member)
        elif found[k + 1][1] == "?." or (k and found[k - 1][1] in _TESTED_BEFORE) or after in _TESTED_AFTER:
            tested.add(member)
        else:
            uses.setdefault(member, []).append(source.count("\n", 0, offset) + 1)
    for k in range(len(found) - 4):
        # Object.defineProperty(window, "X", ...)
        if (found[k][1] == "defineProperty" and found[k + 1][1] == "(" and found[k + 2][1] in names
                and found[k + 3][1] == "," and found[k + 4][0] == "string"):
            result.provides.add(found[k + 4][1])
    result.needs = {member: lines[0] for member, lines in uses.items()
                    if member not in tested and member not in BROWSER_GLOBALS}
    return result


def _window_parameter(found: list[tuple[str, str, int]]) -> set[str]:
    """The parameter of a leading ``(function (global) {`` or ``((global) => {``."""
    for k in range(min(len(found) - 3, 40)):
        if found[k][1] == "function" and found[k + 1][1] == "(" and found[k + 2][0] == "name" and found[k + 3][1] == ")":
            return {found[k + 2][1]}
        if found[k][1] == "(" and found[k + 1][0] == "name" and found[k + 2][1] == ")" and found[k + 3][1] == "=>":
            return {found[k + 1][1]}
    return set()


def script_files() -> dict[str, Path]:
    """Served script name (path under ``/static/``) -> file, vendor libraries included."""
    files: dict[str, Path] = {}
    for root in SCRIPT_ROOTS:
        for path in sorted(root.rglob("*.js")):
            if "node_modules" not in path.parts:
                files.setdefault(path.relative_to(root).as_posix(), path)
    return files


def scan_scripts() -> dict[str, ScriptGlobals]:
    from management_portal.resources.portal import portal_route_script

    files = script_files()
    names = set(files) | {GENERATED}
    scanned = {name: scan(name, path.read_text(encoding="utf-8"), names)
               for name, path in files.items() if not name.startswith(UNSCANNED)}
    scanned[GENERATED] = scan(GENERATED, portal_route_script().decode("utf-8"), names)
    for script in scanned.values():
        script.loads |= {loaded for loaded, member in script.loader_entries
                         if member in scanned.get(loaded, ScriptGlobals(loaded)).provides}
    return scanned


Entry = tuple[str, str]  # ("file", served name) or ("inline", source)
_SCRIPT_ELEMENT = re.compile(r"<script\b([^>]*)>(.*?)</script>", re.S)


def document_scripts(document: str) -> list[Entry]:
    """The scripts of ``document`` in order, as the server sends it."""
    from management_portal import script_groups
    from management_portal.page_bootstrap import inject_page_bootstrap

    sent = inject_page_bootstrap(script_groups.expand_document(document).encode("utf-8")).decode("utf-8")
    entries: list[Entry] = []
    for attributes, body in _SCRIPT_ELEMENT.findall(sent):
        source = re.search(r'\bsrc="([^"]+)"', attributes)
        if source:
            if source.group(1).startswith("/static/"):
                entries.append(("file", source.group(1).partition("?")[0].removeprefix("/static/")))
        elif "application/json" in attributes:
            entries += [("file", path.partition("?")[0].removeprefix("/static/"))
                        for path in _asset_scripts(body) if path.startswith("/static/")]
        elif body.strip() and 'type="module"' not in attributes and "importmap" not in attributes:
            entries.append(("inline", body))
    return entries


def _asset_scripts(body: str) -> list[str]:
    try:
        assets = json.loads(body)
    except ValueError:
        return []
    listed = assets.get("scripts") if isinstance(assets, dict) else None
    return [path for path in listed or () if isinstance(path, str)]


def pages() -> dict[str, list[Entry]]:
    """Page name -> its scripts: every Portal document, Home with its panels, native views in their host."""
    from management_portal import http_portal_pages, portal_features
    from management_portal.page_renderers import render_knowledge_html

    panels = {Path(fragment).name for _feature, fragment in portal_features.contributions("web.home_panel")}
    views = {Path(view["template"]): view["id"] for _feature, view in portal_features.contributions("web.native_view")}
    documents = {}
    for path in sorted(PORTAL.glob("*.html")):
        if path.name in panels or path in views:
            continue
        text = http_portal_pages.home_page(PORTAL).decode("utf-8") if path.name == "index.html" else path.read_text(encoding="utf-8")
        documents[path.name] = document_scripts(text)
    documents["knowledge_board.html"] = document_scripts(render_knowledge_html().decode("utf-8"))
    for template, view in views.items():
        documents[f"{NATIVE_VIEW_HOST} ({view})"] = (
            documents[NATIVE_VIEW_HOST] + document_scripts(template.read_text(encoding="utf-8")))
    return {name: entries for name, entries in documents.items() if entries}


@dataclass(frozen=True)
class Missing:
    script: str
    line: int
    member: str
    providers: tuple[str, ...]
    page: str

    def __str__(self) -> str:
        return f"{self.page}: {self.script}:{self.line} uses window.{self.member} (from {', '.join(self.providers)})"


def missing_globals(scanned: dict[str, ScriptGlobals], documents: dict[str, list[Entry]]) -> list[Missing]:
    """Each global a page's script needs that no script of the page, nor one it loads on demand, provides."""
    providers: dict[str, set[str]] = {}
    for script in scanned.values():
        for member in script.provides:
            providers.setdefault(member, set()).add(script.name)
    found = []
    known = set(scanned)
    for page, entries in documents.items():
        listed = []
        for index, (kind, value) in enumerate(entries):
            if kind == "inline":
                listed.append(scan(f"{page} inline script {index}", value, known))
            elif value in scanned and scanned[value] not in listed:
                listed.append(scanned[value])
        available, pending = set(), [script.name for script in listed]
        loaded = {script.name: script for script in listed}
        while pending:
            name = pending.pop()
            if name in available:
                continue
            available.add(name)
            pending += sorted(loaded.setdefault(each, scanned[each]).name for each in loaded[name].loads if each in scanned)
        provided = set().union(*(loaded[name].provides for name in available))
        for script in listed:
            for member, line in sorted(script.needs.items()):
                if member in providers and member not in provided:
                    found.append(Missing(script.name, line, member, tuple(sorted(providers[member])), page))
    return found


def unknown_scripts(documents: dict[str, list[Entry]]) -> list[tuple[str, str]]:
    """``(page, script)`` for each listed script that is neither a file nor generated."""
    files = set(script_files()) | {GENERATED}
    return [(page, value) for page, entries in documents.items()
            for kind, value in entries if kind == "file" and value not in files]
